"""Write the plain C++ structs of the messages in link/scope.txt (core section 8: one schema defines the interface and
generates the C++ structs and the TypeScript types).

The output, marv/link/messages.hpp, includes no MAVLink header. It holds, in namespace marv::link: an enum class for each
enum of the MARV dialect, one struct per message (fields in XML order, array fields as std::array), the message id
constants and `Message`, the std::variant of the structs in link/scope.txt order. fw/link/src/codec_mavlink.cpp is the
only code that maps these structs to the MAVLink C headers.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mavxml  # noqa: E402

CPP_TYPES = {
    "char": "char",
    "uint8_t": "std::uint8_t",
    "int8_t": "std::int8_t",
    "uint16_t": "std::uint16_t",
    "int16_t": "std::int16_t",
    "uint32_t": "std::uint32_t",
    "int32_t": "std::int32_t",
    "uint64_t": "std::uint64_t",
    "int64_t": "std::int64_t",
    "float": "float",
    "double": "double",
}


def emit(dialect: mavxml.Dialect, scope: list[str]) -> str:
    own = set(dialect.own_enums)
    out = [
        "// Generated by tools/link/gen_cpp_structs.py from link/scope.txt and the MARV dialect. Do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <variant>",
        "",
        "namespace marv::link {",
        "",
    ]
    for name in dialect.own_enums:
        out.append(f"enum class {mavxml.camel(name)} : std::uint8_t {{")
        for entry, value in dialect.enums[name].entries:
            out.append(f"  {mavxml.enum_entry_camel(name, entry)} = {value},")
        out.append("};")
        out.append("")
    for name in scope:
        msg = dialect.messages[name]
        out.append(f"inline constexpr std::uint32_t k{mavxml.camel(name)}Id = {msg.id};")
    out.append("")
    for name in scope:
        msg = dialect.messages[name]
        out.append(f"struct {mavxml.camel(name)} {{")
        for f in msg.fields:
            if f.ctype == "uint8_t_mavlink_version":
                continue
            ctype = mavxml.camel(f.enum) if f.enum in own else CPP_TYPES[f.ctype]
            if f.is_array:
                out.append(f"  std::array<{ctype}, {f.array_len}> {f.name}{{}};")
            else:
                out.append(f"  {ctype} {f.name}{{}};")
        out.append(f"  bool operator==(const {mavxml.camel(name)}&) const = default;")
        out.append("};")
        out.append("")
    out.append("using Message = std::variant<")
    out.append(",\n".join(f"    {mavxml.camel(n)}" for n in scope))
    out.append(">;")
    out.append("")
    out.append("}  // namespace marv::link")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dialect", type=Path, required=True)
    parser.add_argument("--include-dir", type=Path, action="append", default=[])
    parser.add_argument("--scope", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    dialect = mavxml.parse_dialect(args.dialect, args.include_dir)
    text = emit(dialect, mavxml.read_scope(args.scope))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
