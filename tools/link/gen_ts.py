"""Write the TypeScript side of the link codec: typed messages and the wire table of the messages in link/scope.txt.

The output, gcs/src/lib/link/generated/messages.ts, holds the enums of the MARV dialect, one interface per message, the
`Message` union, the per-message wire table (id, CRC_EXTRA, lengths, fields in wire order with their offsets) and the
CRC_EXTRA/length table of every message of the dialect, so that the parser verifies the checksum of a frame it does not
carry exactly as the C++ codec does. The MAVLink v2 framing, the CRC and the table-driven encode and decode are in
gcs/src/lib/link/ (hand written, no runtime dependency); this generator has none either.

Arrays are Uint8Array (char arrays too: the bytes on the wire, no text decoding); 64-bit integers are bigint. A float field
also has an optional `<name>_bits` (the raw uint32): a JavaScript number view of a float cannot hold a signalling-NaN pattern, and
the byte-wise parameter encoding carries INT32 values in a float field, so the codec writes `<name>_bits` when it is set and
sets it on every decoded message.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mavxml  # noqa: E402

TS_SCALAR = {
    "uint8_t": ("u8", "number"),
    "int8_t": ("i8", "number"),
    "uint16_t": ("u16", "number"),
    "int16_t": ("i16", "number"),
    "uint32_t": ("u32", "number"),
    "int32_t": ("i32", "number"),
    "uint64_t": ("u64", "bigint"),
    "int64_t": ("i64", "bigint"),
    "float": ("f32", "number"),
    "double": ("f64", "number"),
}
BYTE_ARRAY_TYPES = {"char", "uint8_t"}


def field_ts_type(f: mavxml.Field, own_enums: set[str]) -> str:
    if f.is_array:
        if f.ctype not in BYTE_ARRAY_TYPES:
            raise ValueError(f"{f.name}: only byte and char arrays are supported, got {f.ctype}[{f.array_len}]")
        return "Uint8Array"
    if f.enum in own_enums:
        return mavxml.camel(f.enum)
    return TS_SCALAR[f.ctype][1]


def wire_kind(f: mavxml.Field) -> str:
    if f.ctype == "uint8_t_mavlink_version":
        return "version"
    if f.ctype == "char":
        return "u8"
    return TS_SCALAR[f.ctype][0]


def emit(dialect: mavxml.Dialect, scope: list[str]) -> str:
    own = set(dialect.own_enums)
    out = [
        "// Generated by tools/link/gen_ts.py from link/scope.txt and the MARV dialect. Do not edit.",
        "",
        "export type WireType = 'u8' | 'i8' | 'u16' | 'i16' | 'u32' | 'i32' | 'u64' | 'i64' | 'f32' | 'f64' | 'version';",
        "",
        "export interface FieldInfo {",
        "\tname: string;",
        "\ttype: WireType;",
        "\t/** 0 for a scalar, else the number of elements (byte arrays only). */",
        "\tlength: number;",
        "\toffset: number;",
        "}",
        "",
        "export interface MessageInfo {",
        "\tkind: string;",
        "\tname: string;",
        "\tid: number;",
        "\tcrcExtra: number;",
        "\t/** Payload bytes without the extension fields. */",
        "\tminLength: number;",
        "\t/** Payload bytes with them. */",
        "\tmaxLength: number;",
        "\t/** In wire order. */",
        "\tfields: FieldInfo[];",
        "}",
        "",
        f"export const MAVLINK_VERSION = {dialect.mavlink_version};",
        "",
    ]
    for name in dialect.own_enums:
        ts = mavxml.camel(name)
        out.append(f"export const {ts} = {{")
        for entry, value in dialect.enums[name].entries:
            out.append(f"\t{mavxml.enum_entry_camel(name, entry)}: {value},")
        out.append("} as const;")
        out.append(f"export type {ts} = (typeof {ts})[keyof typeof {ts}];")
        out.append("")
    for name in scope:
        msg = dialect.messages[name]
        out.append(f"export interface {mavxml.camel(name)} {{")
        for f in msg.fields:
            if f.ctype == "uint8_t_mavlink_version":
                continue
            out.append(f"\t{f.name}: {field_ts_type(f, own)};")
            if not f.is_array and f.ctype == "float":
                out.append(f"\t/** The raw 32 bits of {f.name}: used instead of it when set (encode), always present on a decoded message. */")
                out.append(f"\t{f.name}_bits?: number;")
        out.append("}")
        out.append("")
    out.append("export type Message =")
    for name in scope:
        out.append(f"\t| ({{ kind: '{mavxml.camel(name)}' }} & {mavxml.camel(name)})")
    out[-1] += ";"
    out.append("")
    out.append("export const MESSAGES: MessageInfo[] = [")
    for name in scope:
        msg = dialect.messages[name]
        out.append("\t{")
        out.append(f"\t\tkind: '{mavxml.camel(name)}',")
        out.append(f"\t\tname: '{name}',")
        out.append(f"\t\tid: {msg.id},")
        out.append(f"\t\tcrcExtra: {msg.crc_extra},")
        out.append(f"\t\tminLength: {msg.min_len},")
        out.append(f"\t\tmaxLength: {msg.max_len},")
        out.append("\t\tfields: [")
        for f in msg.wire:
            out.append(
                f"\t\t\t{{ name: '{f.name}', type: '{wire_kind(f)}', length: {f.array_len}, offset: {f.offset} }},"
            )
        out.append("\t\t]")
        out.append("\t},")
    out.append("];")
    out.append("")
    out.append("/** CRC_EXTRA and maximum payload length of every message of the dialect, by message id. */")
    out.append("export const DIALECT: Record<number, { crcExtra: number; maxLength: number }> = {")
    for msg in sorted(dialect.messages.values(), key=lambda m: m.id):
        out.append(f"\t{msg.id}: {{ crcExtra: {msg.crc_extra}, maxLength: {msg.max_len} }},")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dialect", type=Path, required=True)
    parser.add_argument("--include-dir", type=Path, action="append", default=[])
    parser.add_argument("--scope", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    dialect = mavxml.parse_dialect(args.dialect, args.include_dir)
    text = emit(dialect, mavxml.read_scope(args.scope))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
