#!/usr/bin/env python3
"""The fake vehicle of the GCS end-to-end test (GCS-first unit GX-0; tools/gs/e2e.sh). A test tool, never flown.

It stands where the SIL's link service stands: a UDP socket on 127.0.0.1:<port>. Like the SIL, it answers the sender of its
latest datagram (the helper announces itself with an empty datagram when it opens the device and keeps doing so), and it sends
nothing before the first datagram. The wire is the pymavlink dialect generated by mavgen from link/marv.xml and the pinned
standard definitions (tools/link/fetch_defs.py), cached in --defs-dir; pymavlink is a dev dependency.

What it does is what gcs/src/lib/link/vehicle.ts lists for a vehicle, with a few parameters: a heartbeat every
--heartbeat-s; the identity and the version on a REQUEST_MESSAGE command; one value and one provenance record per parameter on
a list or index request; a parameter write answered with the staged value (a locked parameter refused with a status text);
the source text read in chunks; the telemetry streams of the live view (SET_MESSAGE_INTERVAL starts and stops each of the nine
streams at the interval asked, at most one message per receive wait; the values are a slow harness motion, not a model). PARAM_VALUE carries the raw 32 bits of the value (the version advertises bytewise encoding).
Values are chosen so that no bit pattern is a NaN. Config commands are answered "unavailable".

The radio (GX-7): its parameters are the register's channel map (rc_channel_* = 1 2 3 4 roll to yaw, arm 5, angle 8) and thresholds, a
write of a channel parameter that would make the stick, arm and angle channels not pairwise distinct (rule R-1) is refused as the
vehicle's composition validate refuses it, and a parameter's source text can be written (MARV_PARAM_SOURCE set). The RC stream moves
channel 1 by a small swing (below a switch's travel) and channel 14 as a switch (down, then up, every RC_SWITCH_PERIOD_S): the
radio that sends its angle switch on a channel the parameters do not name.

  uv run python tools/gs/e2e_fake_vehicle.py --udp-port N --defs-dir DIR [--heartbeat-s S]
  uv run python tools/gs/e2e_fake_vehicle.py --manifest-out FILE      (the parameter manifest of this vehicle, for the image library)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import importlib.util
import signal
import socket
import struct
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

SYSTEM_ID, COMPONENT_ID = 1, 1  # the SIL link service's address
GCS_SYSTEM_ID, GCS_COMPONENT_ID = 255, 190  # the ground-station convention
DEFAULT_HEARTBEAT_S = 1.0  # labelled harness value: the conventional 1 Hz heartbeat
POLL_S = 0.05  # labelled harness value: one receive wait
CHUNK = 64  # MARV_PARAM_SOURCE.chunk
CMD_REQUEST_MESSAGE = 512
CMD_SET_MESSAGE_INTERVAL = 511
RESULT_ACCEPTED, RESULT_UNSUPPORTED = 0, 3
US_PER_S = 1_000_000
# The telemetry streams (message id -> pymavlink message name) the fake vehicle can send.
STREAMS = {1: "sys_status", 30: "attitude", 31: "attitude_quaternion", 65: "rc_channels", 83: "attitude_target", 105: "highres_imu",
           375: "actuator_output_status", 15205: "marv_fc_status", 15206: "marv_estimator"}
# Harness values of the fake motion: the angle swing (rad), its period (s), the stick centre and half span (us) and the DShot swing.
SWING_RAD, SWING_PERIOD_S = 0.3, 6.0
RC_CENTRE_US, RC_HALF_SPAN_US = 1500, 512
# The fake radio (GX-7), harness values: channel 1 swings by RC_SWING_US (less than a switch's travel), channel 14 is a switch that goes down
# and up every RC_SWITCH_PERIOD_S, the throttle (3), the arm switch (5) and the angle switch (8) rest at the low end of the range.
RC_SWING_US, RC_SWITCH_PERIOD_S, RC_SWITCH_CHANNEL = 100, 8.0, 14
RC_LOW_US, RC_HIGH_US = 988, 2012
DSHOT_BASE, DSHOT_SWING = 1000, 200
MSG_AUTOPILOT_VERSION, MSG_MARV_IDENTITY = 148, 15200
CAPABILITY_PARAM_ENCODE_BYTEWISE = 16
TYPE_INT32, TYPE_REAL32 = 6, 9
SOURCE_OP_READ, SOURCE_OP_DATA, SOURCE_OP_SET = 0, 1, 2
RESULT_DENIED_UNAVAILABLE = 4
SEVERITY_WARNING = 4

# The identity the end-to-end spec expects: SHA-256 of these texts (gcs/e2e/connection.spec.ts computes the same).
IMAGE_TEXT = "marv-e2e-fake-image"
CONFIG_TEXT = "marv-e2e-fake-config"
SCHEMA_HASH = 0x0123456789ABCDEF

# (link id, type, raw value bits, locked, source text). Each bit pattern is a finite float or a small integer.
def _f32(value: float) -> int:
    return struct.unpack("<I", struct.pack("<f", value))[0]


FAKE = "fake vehicle of the GCS e2e test"
# The thresholds are the register's 1700 us: (1700 - 1500) / 512 (fw quad_fc_register.yaml arm_switch_threshold).
SWITCH_THRESHOLD = (1700 - 1500) / 512
PARAMS = (
    ("att_kp", TYPE_REAL32, _f32(1.5), False, FAKE),
    ("rate_kp_roll", TYPE_REAL32, _f32(0.25), False, FAKE),
    ("rc_channel_roll", TYPE_INT32, 1, False, FAKE),
    ("rc_channel_pitch", TYPE_INT32, 2, False, FAKE),
    ("rc_channel_throttle", TYPE_INT32, 3, False, FAKE),
    ("rc_channel_yaw", TYPE_INT32, 4, False, FAKE),
    ("rc_channel_arm", TYPE_INT32, 5, True, "locked in the fake vehicle, as the arm channel is on the real one"),
    ("rc_channel_angle", TYPE_INT32, 8, False, FAKE),
    ("arm_switch_threshold", TYPE_REAL32, _f32(SWITCH_THRESHOLD), True, "locked in the fake vehicle, as on the real one"),
    ("angle_switch_threshold", TYPE_REAL32, _f32(SWITCH_THRESHOLD), False, FAKE),
    ("arm_throttle_min", TYPE_REAL32, _f32((1050 - 988) / 1024), True, "locked in the fake vehicle, as on the real one"),
)
# The channel parameters that rule R-1 compares (the angle channel 0 = none), by name.
CHANNEL_PARAMS = ("rc_channel_roll", "rc_channel_pitch", "rc_channel_throttle", "rc_channel_yaw", "rc_channel_arm", "rc_channel_angle")


def load_dialect(defs_dir: Path):
    out = defs_dir / "marv_dialect.py"
    if not out.exists():
        subprocess.run([sys.executable, str(ROOT / "tools" / "link" / "fetch_defs.py"), "--out-dir", str(defs_dir)],
                       check=True, capture_output=True)
        subprocess.run([sys.executable, "-m", "pymavlink.tools.mavgen", "--lang", "Python3", "--wire-protocol", "2.0",
                        "--output", str(out), str(defs_dir / "marv.xml")], check=True, capture_output=True)
    spec = importlib.util.spec_from_file_location("marv_dialect", out)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def raw_float(bits: int) -> float:
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def raw_bits(value: float) -> int:
    return struct.unpack("<I", struct.pack("<f", value))[0]


class Peer:
    """The file the dialect writes to: each frame goes to the sender of the latest datagram, once there is one."""

    def __init__(self, sock: socket.socket):
        self.sock = sock
        self.addr = None

    def write(self, data: bytes) -> None:
        if self.addr is not None:
            self.sock.sendto(bytes(data), self.addr)


class Vehicle:
    def __init__(self, dialect, sock: socket.socket):
        self.d = dialect
        self.peer = Peer(sock)
        self.mav = dialect.MAVLink(self.peer, SYSTEM_ID, COMPONENT_ID)
        self.rx = dialect.MAVLink(None, SYSTEM_ID, COMPONENT_ID)
        self.staged = [p[2] for p in PARAMS]
        self.active = [p[2] for p in PARAMS]
        self.text = [p[4] for p in PARAMS]
        self.interval_s: dict[int, float] = {}
        self.due: dict[int, float] = {}
        self.t0 = time.monotonic()

    def send_named(self, name: str, **values) -> None:
        """Sends the message `name`; a field not given is zero (an array of zeros)."""
        cls = getattr(self.d, f"MAVLink_{name}_message")
        args = [values.get(f, [0] * n if n else 0) for f, n in zip(cls.fieldnames, cls.array_lengths)]
        self.mav.send(cls(*args))

    def step_streams(self, now: float) -> None:
        """Sends each running stream that is due, once; the next is due one interval later (or one from now when it fell behind)."""
        for msg_id, interval in self.interval_s.items():
            if now < self.due[msg_id]:
                continue
            self.stream(msg_id, now - self.t0)
            self.due[msg_id] = max(self.due[msg_id] + interval, now)

    def stream(self, msg_id: int, t: float) -> None:
        swing = SWING_RAD * math.sin(2 * math.pi * t / SWING_PERIOD_S)
        ms, us = int(t * 1000), int(t * US_PER_S)
        name = STREAMS[msg_id]
        if name == "sys_status":
            self.send_named(name, onboard_control_sensors_present=0x210003, onboard_control_sensors_enabled=0x210003,
                            onboard_control_sensors_health=0x210003, voltage_battery=0xFFFF, current_battery=-1, battery_remaining=-1)
        elif name == "attitude":
            self.send_named(name, time_boot_ms=ms, roll=swing, pitch=-swing / 2, yaw=swing * 2, rollspeed=0.1, pitchspeed=-0.2, yawspeed=0.3)
        elif name == "attitude_quaternion":
            h = swing / 2
            self.send_named(name, time_boot_ms=ms, q1=math.cos(h), q2=math.sin(h), q3=0.0, q4=0.0)
        elif name == "rc_channels":
            ch = {f"chan{i + 1}_raw": RC_CENTRE_US for i in range(16)}
            ch["chan1_raw"] = RC_CENTRE_US + int(RC_SWING_US * math.sin(2 * math.pi * t / SWING_PERIOD_S))
            ch["chan3_raw"] = ch["chan5_raw"] = ch["chan8_raw"] = RC_LOW_US
            ch[f"chan{RC_SWITCH_CHANNEL}_raw"] = RC_LOW_US if (t % RC_SWITCH_PERIOD_S) < RC_SWITCH_PERIOD_S / 2 else RC_HIGH_US
            ch["chan17_raw"] = ch["chan18_raw"] = 0xFFFF
            self.send_named(name, time_boot_ms=ms, chancount=16, rssi=190, **ch)
        elif name == "attitude_target":
            self.send_named(name, time_boot_ms=ms, type_mask=128, q=[1.0, 0.0, 0.0, 0.0], body_roll_rate=0.5, thrust=0.25)
        elif name == "highres_imu":
            self.send_named(name, time_usec=us, xacc=0.1, yacc=-0.2, zacc=-9.8, xgyro=0.1, ygyro=-0.2, zgyro=0.3, temperature=31.5,
                            fields_updated=0x103F)
        elif name == "actuator_output_status":
            self.send_named(name, time_usec=us, active=0xF, actuator=[float(DSHOT_BASE + DSHOT_SWING * i) for i in range(4)] + [0.0] * 28)
        elif name == "marv_fc_status":
            self.send_named(name, time_usec=us, rate_executions=us // 1000, rc_frames=1, rc_age_us=20000, arm_state=1, motor_gate=0, flags=8 | 16 | 32)
        elif name == "marv_estimator":
            h = swing / 2
            self.send_named(name, time_usec=us, q_mahony=[math.cos(h), math.sin(h), 0.0, 0.0], q_eskf=[1.0, 0.0, 0.0, 0.0], flags=1)

    def collides(self, name: str, bits: int) -> bool:
        """Rule R-1 on the staged table with `name` set to `bits`: the stick, arm and angle channels pairwise distinct, angle 0 = none."""
        channel = {n: self.staged[i] for i, (n, *_rest) in enumerate(PARAMS) if n in CHANNEL_PARAMS}
        channel[name] = bits
        used = [v for n, v in channel.items() if not (n == "rc_channel_angle" and v == 0)]
        return len(set(used)) != len(used)

    def set_interval(self, m) -> None:
        msg_id = int(m.param1)
        result = RESULT_ACCEPTED
        if msg_id not in STREAMS:
            result = RESULT_UNSUPPORTED
        elif m.param2 in (0, -1):
            self.interval_s.pop(msg_id, None)
        else:
            self.interval_s[msg_id] = m.param2 / US_PER_S
            self.due[msg_id] = time.monotonic()
        self.mav.command_ack_send(m.command, result, 0, 0, GCS_SYSTEM_ID, GCS_COMPONENT_ID)

    def heartbeat(self) -> None:
        self.mav.heartbeat_send(2, 0, 0, 0, 4)  # type quadrotor, no autopilot class, disarmed, system status standby

    def status(self, text: str) -> None:
        self.mav.statustext_send(SEVERITY_WARNING, text.encode()[:50])

    def identity(self) -> None:
        self.mav.marv_identity_send(
            SCHEMA_HASH, hashlib.sha256(IMAGE_TEXT.encode()).digest(), hashlib.sha256(CONFIG_TEXT.encode()).digest(),
            bytes(32), 0, 0, 0, 0, int(self.staged != self.active))

    def version(self) -> None:
        self.mav.autopilot_version_send(CAPABILITY_PARAM_ENCODE_BYTEWISE, 0, 0, 0, 0, bytes(8), bytes(8), bytes(8), 0, 0, 0, bytes(18))

    def value(self, i: int) -> None:
        self.mav.param_value_send(PARAMS[i][0].encode(), raw_float(self.staged[i]), PARAMS[i][1], len(PARAMS), i)

    def record(self, i: int) -> None:
        chunk = self.text[i].encode()[:CHUNK]
        self.mav.marv_param_record_send(
            self.active[i], self.staged[i], 0.0, i, len(PARAMS), len(self.text[i].encode()), 1, 5, 1, int(PARAMS[i][3]),
            len(chunk), chunk.ljust(CHUNK, b"\0"))

    def param(self, i: int) -> None:
        self.value(i)
        self.record(i)

    def handle(self, m) -> None:
        kind = m.get_type()
        if kind == "COMMAND_LONG" and m.command == CMD_SET_MESSAGE_INTERVAL:
            self.set_interval(m)
        elif kind == "COMMAND_LONG" and m.command == CMD_REQUEST_MESSAGE:
            if int(m.param1) == MSG_MARV_IDENTITY:
                self.identity()
            elif int(m.param1) == MSG_AUTOPILOT_VERSION:
                self.version()
        elif kind == "PARAM_REQUEST_LIST":
            for i in range(len(PARAMS)):
                self.param(i)
        elif kind == "PARAM_REQUEST_READ" and 0 <= m.param_index < len(PARAMS):
            self.param(m.param_index)
        elif kind == "PARAM_SET":
            name = m.param_id.rstrip("\0") if isinstance(m.param_id, str) else m.param_id.decode().rstrip("\0")
            index = next((i for i, p in enumerate(PARAMS) if p[0] == name), None)
            if index is None:
                self.status(f"refused: no parameter {name}")
            elif PARAMS[index][3]:
                self.status(f"refused: {name}: locked, keeps its compiled value")
                self.value(index)
            elif m.param_type != PARAMS[index][1]:
                self.status(f"refused: {name}: type differs from the record")
                self.value(index)
            elif name in CHANNEL_PARAMS and self.collides(name, raw_bits(m.param_value)):
                self.status(f"refused: {name}: channel in use (R-1)")  # at most STATUS_TEXT bytes
                self.value(index)
            else:
                self.staged[index] = raw_bits(m.param_value)
                self.value(index)
        elif kind == "MARV_PARAM_SOURCE" and m.operation == SOURCE_OP_SET and 0 <= m.param_index < len(PARAMS):
            chunk = bytes(m.chunk[: m.chunk_length]) if not isinstance(m.chunk, str) else m.chunk.encode()[: m.chunk_length]
            text = self.text[m.param_index].encode() if m.offset else b""
            self.text[m.param_index] = (text[: m.offset] + chunk).decode()
        elif kind == "MARV_PARAM_SOURCE" and m.operation == SOURCE_OP_READ and 0 <= m.param_index < len(PARAMS):
            text = self.text[m.param_index].encode()
            chunk = text[m.offset:m.offset + CHUNK]
            self.mav.marv_param_source_send(SCHEMA_HASH, m.param_index, m.offset, len(text), GCS_SYSTEM_ID, GCS_COMPONENT_ID,
                                            SOURCE_OP_DATA, len(chunk), chunk.ljust(CHUNK, b"\0"))
        elif kind == "MARV_CONFIG_COMMAND":
            self.mav.marv_config_ack_send(GCS_SYSTEM_ID, GCS_COMPONENT_ID, m.action, RESULT_DENIED_UNAVAILABLE)

    def feed(self, data: bytes) -> None:
        for byte in data:
            try:
                m = self.rx.parse_char(bytes([byte]))
            except Exception:  # a frame the dialect cannot decode is dropped, as a vehicle drops it
                continue
            if m is not None:
                self.handle(m)


def manifest() -> dict:
    """The parameter manifest of this vehicle in the form tools/gen/params_gen.py writes (the part the GCS reads), keyed by the vehicle's schema hash."""
    params = {
        name: {"id": i, "type": "f32" if kind == TYPE_REAL32 else "i32", "unit": "1", "link_id": name, "lock": locked,
               "default_bits": f"0x{bits:08x}", "method": "scenario", "sigma_kind": "Choice", "sigma": 0.0, "sigma_bits": "0x00000000",
               "origin": "DefaultFromCard", "source": text, "source_file": "e2e_fake_vehicle.py"}
        for i, (name, kind, bits, locked, text) in enumerate(PARAMS)
    }
    return {"schema_hash": f"0x{SCHEMA_HASH:016x}", "count": len(params), "params": params}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--udp-port", type=int, help="UDP port on 127.0.0.1 (the helper's --sil-udp-port)")
    ap.add_argument("--defs-dir", type=Path, help="cache of the pinned definitions and the generated dialect")
    ap.add_argument("--heartbeat-s", type=float, default=DEFAULT_HEARTBEAT_S)
    ap.add_argument("--manifest-out", type=Path, help="write the parameter manifest of this vehicle to FILE and exit")
    args = ap.parse_args(argv)
    if args.manifest_out is not None:
        args.manifest_out.write_text(json.dumps(manifest()))
        return 0
    if args.udp_port is None or args.defs_dir is None:
        ap.error("--udp-port and --defs-dir are required")
    dialect = load_dialect(args.defs_dir)
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind(("127.0.0.1", args.udp_port))
    sock.settimeout(POLL_S)
    vehicle = Vehicle(dialect, sock)
    running = [True]
    for sig in (signal.SIGINT, signal.SIGTERM):
        signal.signal(sig, lambda *_: running.__setitem__(0, False))
    print(f"fake vehicle on udp 127.0.0.1:{args.udp_port}", flush=True)
    next_beat = time.monotonic()
    while running[0]:
        try:
            data, addr = sock.recvfrom(65535)
            vehicle.peer.addr = addr
            vehicle.feed(data)
        except socket.timeout:
            pass
        if vehicle.peer.addr is not None:
            vehicle.step_streams(time.monotonic())
        if vehicle.peer.addr is not None and time.monotonic() >= next_beat:
            vehicle.heartbeat()
            next_beat = time.monotonic() + args.heartbeat_s
    sock.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
