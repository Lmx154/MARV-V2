def load_dialect(xml: Path = DIALECT_XML):
    out = Path(tempfile.mkdtemp(prefix="marv_dialect_")) / "marv_dialect.py"
    subprocess.run([sys.executable, "-m", "pymavlink.tools.mavgen", "--lang", "Python3", "--wire-protocol", "2.0", "--output",
                    str(out), str(xml)], check=True, capture_output=True)
    spec = importlib.util.spec_from_file_location("marv_dialect", out)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class HelperProcess:
    """tools/gs/helper.py on the board's link port, on a free localhost port; its URL gives the port and the session token."""

    def __init__(self, runs_dir: Path, serial: str = LINK):
        runs_dir.mkdir(parents=True, exist_ok=True)
        self.proc = subprocess.Popen([sys.executable, str(HELPER), "--serial", serial, "--port", "0", "--runs-dir", str(runs_dir),
                                      "--build-root", str(ROOT / "build")],
                                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, start_new_session=True)
        self.lines = []
        deadline = time.monotonic() + HELPER_START_S
        self.url = self.run_dir = None
        while time.monotonic() < deadline and (self.url is None or self.run_dir is None):
            line = self.proc.stdout.readline()
            if not line:
                break
            self.lines.append(line.rstrip("\n"))
            if line.startswith("GCS:"):
                self.url = line.split(None, 1)[1].strip()
            elif line.startswith("run dir:"):
                self.run_dir = Path(line.split(":", 1)[1].strip())
        if self.url is None:
            self.stop()
            raise RuntimeError("the helper did not start:\n" + "\n".join(self.lines))
        m = re.match(r"http://127\.0\.0\.1:(\d+)/\?token=(\S+)", self.url)
        self.port, self.token = int(m.group(1)), m.group(2)
        self.origin = f"http://127.0.0.1:{self.port}"

    def stop(self):
        if self.proc.poll() is None:
            os.killpg(self.proc.pid, signal.SIGTERM)
            try:
                self.proc.wait(10)
            except subprocess.TimeoutExpired:
                os.killpg(self.proc.pid, signal.SIGKILL)
                self.proc.wait()
        rest = self.proc.stdout.read() if self.proc.stdout else ""
        self.lines.extend(rest.splitlines())


class WsPipe:
    """Raw device bytes through the helper's WebSocket (binary frames both ways)."""

    def __init__(self, helper: HelperProcess):
        from websockets.sync.client import connect
        self.ws = connect(f"ws://127.0.0.1:{helper.port}/ws?token={helper.token}", origin=helper.origin, compression=None)

    def write(self, data: bytes):
        self.ws.send(data)

    def read(self, timeout: float) -> bytes:
        try:
            msg = self.ws.recv(timeout=timeout)
        except TimeoutError:
            return b""
        return msg if isinstance(msg, bytes) else b""

    def close(self):
        self.ws.close()


class SerialPipe:
    """Raw bytes on the link port itself (DTR asserted)."""

    def __init__(self, dev: str = LINK):
        self.fd = open_raw(dev)

    def write(self, data: bytes):
        view = memoryview(data)
        while view:
            try:
                n = os.write(self.fd, view)
            except BlockingIOError:
                select.select([], [self.fd], [], POLL_S)
                continue
            view = view[n:]

    def read(self, timeout: float) -> bytes:
        ready, _, _ = select.select([self.fd], [], [], timeout)
        if not ready:
            return b""
        try:
            return os.read(self.fd, 65536)
        except (BlockingIOError, OSError):
            return b""

    def close(self):
        os.close(self.fd)


class Client:
    """The ground station's side on a pipe; every message received is kept in order with its host arrival time."""

    def __init__(self, d, pipe):
        self.d, self.pipe = d, pipe
        self.mav = d.MAVLink(None, srcSystem=GCS_SYSTEM, srcComponent=GCS_COMPONENT)
        self.parser = d.MAVLink(None)
        self.parser.robust_parsing = True
        self.got = []  # (host time, message)
        self.rx_bytes = 0

    def send(self, message):
        self.pipe.write(message.pack(self.mav))

    def pump(self, timeout=POLL_S):
        data = self.pipe.read(timeout)
        if data:
            self.rx_bytes += len(data)
            now = time.time()
            self.got.extend((now, m) for m in self.parser.parse_buffer(data) or [])

    def mark(self):
        return len(self.got)

    def messages(self, after=0):
        return [m for _, m in self.got[after:]]

    def since(self, after, name):
        return [m for _, m in self.got[after:] if m.get_type() == name]

    def wait(self, predicate, what, after=0, timeout=REPLY_S):
        deadline = time.monotonic() + timeout
        i = after
        while True:
            for k in range(i, len(self.got)):
                if predicate(self.got[k][1]):
                    return self.got[k][1]
            i = len(self.got)
            if time.monotonic() > deadline:
                raise TimeoutError(f"no {what} within {timeout} s")
            self.pump()

    def listen(self, seconds):
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            self.pump()

    def seq_gaps(self, after=0):
        """Frames the board sent but this client never decoded: the gaps in the vehicle's sequence numbers."""
        seqs = [m.get_seq() for _, m in self.got[after:] if m.get_srcSystem() == VEHICLE[0]]
        return sum(((b - a) % 256) - 1 for a, b in zip(seqs, seqs[1:]))

    # ---- requests ---------------------------------------------------------------------------------------------------

    def heartbeat(self):
        return self.wait(lambda m: m.get_type() == "HEARTBEAT", "HEARTBEAT", self.mark())

    def request_message(self, msg_id, name):
        at = self.mark()
        self.send(self.d.MAVLink_command_long_message(*VEHICLE, self.d.MAV_CMD_REQUEST_MESSAGE, 0, float(msg_id), 0, 0, 0, 0, 0, 0))
        return self.wait(lambda m: m.get_type() == name, name, at)

    def identity(self):
        return self.request_message(self.d.MAVLINK_MSG_ID_MARV_IDENTITY, "MARV_IDENTITY")

    def version(self):
        return self.request_message(self.d.MAVLINK_MSG_ID_AUTOPILOT_VERSION, "AUTOPILOT_VERSION")

    def list_all(self, count, timeout=REPLY_S):
        """PARAM_REQUEST_LIST, then every PARAM_VALUE and MARV_PARAM_RECORD of the listing by index."""
        at = self.mark()
        t0 = time.monotonic()
        self.send(self.d.MAVLink_param_request_list_message(*VEHICLE))
        for i in range(count):
            self.wait(lambda m, i=i: m.get_type() == "MARV_PARAM_RECORD" and m.param_index == i, f"MARV_PARAM_RECORD {i}", at, timeout)
        elapsed = time.monotonic() - t0
        values = {m.param_index: m for m in self.since(at, "PARAM_VALUE")}
        records = {m.param_index: m for m in self.since(at, "MARV_PARAM_RECORD")}
        return values, records, elapsed, at

    def read(self, index):
        at = self.mark()
        self.send(self.d.MAVLink_param_request_read_message(*VEHICLE, b"", index))
        value = self.wait(lambda m: m.get_type() == "PARAM_VALUE" and m.param_index == index, f"PARAM_VALUE {index}", at)
        record = self.wait(lambda m: m.get_type() == "MARV_PARAM_RECORD" and m.param_index == index, f"MARV_PARAM_RECORD {index}", at)
        return value, record

    def set(self, link_id, bits, wire_type):
        at = self.mark()  # byte-wise encoding: the 32 bits ride in the float field for either type
        self.send(self.d.MAVLink_param_set_message(*VEHICLE, link_id.encode(), f32_of(bits), wire_type))
        return self.wait(lambda m: m.get_type() == "PARAM_VALUE" and m.param_id == link_id, f"PARAM_VALUE {link_id}", at), at

    def config(self, action, report_id, expected, schema_hash):
        at = self.mark()
        self.send(self.d.MAVLink_marv_config_command_message(schema_hash, list(report_id), list(expected), *VEHICLE, action))
        return self.wait(lambda m: m.get_type() == "MARV_CONFIG_ACK", "MARV_CONFIG_ACK", at), at

    def texts(self, after):
        return [m.text for m in self.since(after, "STATUSTEXT")]


def f32_of(bits):
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def payload(d, m):
    """The message's payload bytes, MAVLink 2's trailing-zero truncation undone."""
    frame = bytes(m.get_msgbuf())
    assert frame[0] == d.PROTOCOL_MARKER_V2
    return frame[d.HEADER_LEN_V2:d.HEADER_LEN_V2 + frame[1]].ljust(type(m).unpacker.size, b"\0")


def value_bits(d, m):
    assert type(m).ordered_fieldnames[0] == "param_value"
    return struct.unpack_from("<I", payload(d, m), 0)[0]


def staged_config(factory_cfg, manifest, changes):
    """The factory config with `changes` {index: Record} applied: what the store stages and hashes."""
    records = mcfg.section_records(factory_cfg.section("quad"))
    for i, r in changes.items():
        records[i] = r
    return mcfg.Config(0, bytes(mcfg.DIGEST), bytes(mcfg.DIGEST),
                       (mcfg.build_section("quad", mcfg.manifest_schema_hash(manifest), records),))


def console_fields(reader: ConsoleReader):
    """The newest stats line's fields the checks read, or None before the first."""
    m = reader.last(r"imu dt=.*")
    if m is None:
        return None
    line = m.group(0)
    get = lambda pat: (re.search(pat, line) or [None, None])[1]  # noqa: E731
    return {
        "t_us": int(get(r"\| t=(\d+)")),
        "est_valid": int(get(r"est_valid=(\d)")),
        "arming": get(r"arming=(\w+)"),
        "rate_timing_faults": int(get(r"executions=\d+ timing_faults=(\d+)")),
        "attitude_timing_faults": int(get(r"attitude faults=\d+ timing_faults=(\d+)")),
        "usb_reset_refused": int(get(r"usb_reset_refused=(\d+)")),
        "imu_faults": get(r"(ovr=\d+ spi=\d+ partial=\d+ clamp=\d+ order=\d+ empty=\d+)"),
        "line": line,
    }


def wait_console(reader: ConsoleReader, seconds=REPLY_S):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        f = console_fields(reader)
        if f is not None:
            return f
        time.sleep(POLL_S)
    raise TimeoutError("no console stats line")


def sha256_hex(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()
