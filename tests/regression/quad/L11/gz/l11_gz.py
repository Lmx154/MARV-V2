"""Helpers of the L11 gz suite (conftest.py): the L5-style world of a short run on the host-gz-l11 or the host-gz-l5 build.

World. The L5 scenario step_roll (scenarios/quad/L05/step_roll.yaml), planned by run_l5.plan against the build's own
parameter table, written as the L2-schema world input (run_l5.l2_scenario_doc), generated by gen_world at m = M and edited
by run_l5.world_edit: the composition's overrides, the truth gyro and, unless left out, the truth attitude; `vertical` adds
<vertical_source>truth</vertical_source> inside the plugin element. On the host-gz-l11 build the overrides are the L11
composition's (decision 0020 section 4): vert_hover_thrust_n the plan's hover thrust (float32 of m g(phi, h0),
run_l4.hover_thrust's rule) and one script segment from stamp 0 with the neutral sticks and z_ref the scenario's initial
down position, so the run starts at the reference; on the host-gz-l5 build they are the plan's L5 overrides. A run is one
`gz sim` process of `iterations` host steps (run_scenario.run_gz_process), its stderr kept for the refusal tests.
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(ROOT / "tools" / "card"))
sys.path.insert(0, str(ROOT / "tools" / "sim"))
import gen_world  # noqa: E402
import l5_scenario as l5s  # noqa: E402
import run_l5  # noqa: E402
import run_l11  # noqa: E402
import run_scenario  # noqa: E402

l4 = run_l5.l4
CARD = ROOT / "vehicles" / "uzh_neurobem_5in.yaml"
SOURCE = ROOT / "scenarios" / "quad" / "L05" / "step_roll.yaml"
PLUGIN_DIR_L11 = ROOT / "build" / "host-gz-l11" / "sim" / "gz" / "plugin"
PLUGIN_DIR_L5 = run_l5.DEFAULT_PLUGIN_DIR
L11_PARAMS = "marv_params_l11_vertical_scripted"
VERTICAL_ELEMENT = run_l11.VERTICAL_ELEMENT
M = 2  # step_roll's first m (its m_sequence [2, 1])
ITERATIONS = 64  # labelled harness value: host steps of a short run, enough for the falling start to move z and v_z
TIMEOUT_S = 180
VALID = 1  # bit MARV_TRUTH_VERTICAL_VALID (fw/sil/include/marv_truth_vertical.h)
REFUSED = "marv_gz_lockstep: REFUSED: "
NEEDS_ATTITUDE = "<vertical_source> needs <attitude_source>truth</attitude_source>"
NEEDS_LIBRARY = ("<vertical_source> needs a SIL library with marv_truth_vertical_set (built with TRUTH_VERTICAL, target "
                 "property MARV_SIL_TRUTH_VERTICAL); the linked one has none")


def build_parameters(plugin_dir, name):
    """The parameter table (name -> value) of the build that holds plugin_dir; `name` is that build's MARV_GZ_PARAMS (the
    runners' build_parameters refuse any other build)."""
    _, defaults = (run_l11 if name == L11_PARAMS else run_l5).build_parameters(plugin_dir)
    return l4.read_param_defaults(defaults)


def z_ref_m():
    """The script's height reference: the scenario's initial down position, float32."""
    return l4.r32(l5s.values(l5s.load(SOURCE))["initial_state"]["position_ned_m"][2])


def world(tmp, log, *, l11=True, attitude=True, vertical=True, hover_scale=1):
    """The world text (module docstring) with its <log_path> at `log`. `hover_scale` multiplies the hover thrust before its
    float32 cast (the bracket control)."""
    plugin_dir = PLUGIN_DIR_L11 if l11 else PLUGIN_DIR_L5
    doc = l5s.load(SOURCE)
    p = run_l5.plan(doc, build_parameters(plugin_dir, L11_PARAMS if l11 else run_l5.COMPOSITION_PARAMS), CARD)
    stem = f"{doc['scenario']}_{run_l5.NAME_LABEL}"
    l2 = Path(tmp) / f"{stem}.yaml"
    l2.write_text(yaml.safe_dump(run_l5.l2_scenario_doc(doc, p, stem, SOURCE.name, CARD), sort_keys=False),
                  encoding="utf-8")
    text = gen_world.generate(CARD, l2, "test", M, None, str(log), ROOT)[1]
    if l11:
        overrides = {"vert_hover_thrust_n": (l4.F32, repr(l4.r32(p.thrust_n_double * hover_scale))),
                     "l11_seg_count": (l4.I32, "1"), "l11_seg1_t_us": (l4.I32, "0"),
                     "l11_seg1_z_ref_m": (l4.F32, repr(z_ref_m()))}
    else:
        overrides = p.overrides()
    return run_l5.world_edit(overrides, run_l11.add_vertical if vertical else None, attitude_source=attitude)(text)


def run(text, tmp, plugin_dir, iterations=ITERATIONS):
    sdf = Path(tmp) / "world.sdf"
    sdf.write_text(text, encoding="utf-8")
    seed = l5s.values(l5s.load(SOURCE))["seed"]
    return run_scenario.run_gz_process(sdf, iterations, seed, plugin_dir, None, TIMEOUT_S)
