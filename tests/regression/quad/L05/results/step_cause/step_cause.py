import hashlib
import math
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[5]
sys.path.insert(0, str(ROOT / "tools" / "sim"))
sys.path.insert(0, str(ROOT / "tools" / "card"))
sys.path.insert(0, str(ROOT / "tools" / "refdata"))
sys.path.insert(0, str(ROOT / "tests" / "regression" / "quad" / "L05" / "gz"))
import refdata  # noqa: E402
import run_l4  # noqa: E402
import run_l5  # noqa: E402
import test_t4_steps as t4  # noqa: E402

CARD = ROOT / "vehicles" / "uzh_neurobem_5in.yaml"
SCEN = ROOT / "scenarios" / "quad" / "L05"
T3_GENERATED = refdata.reference_dir("quad/L05/t3")  # the generated golden, envelope and q (decision 0011)
MODES = ("design", "cont", "quant", "quant_gyro")
SUBSTEPS = (1, 2)
L4_F_RAD_S = 0.0409  # cited: decision 0005 "T4 per-axis steps (result, 2026-09-30)", F = 0.0409 rad/s


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def hexf(x):
    return struct.pack("<f", x)[::-1].hex()


def card_of(sdf_path):
    root = ET.parse(sdf_path).getroot()
    plug = root.find(".//plugin[@name='marv::gz::Lockstep']")
    inert = root.find(".//inertial/inertia")
    g = lambda t: float(plug.find(t).text)  # noqa: E731
    rotors = [(int(r.get("motor")), [float(v) for v in r.find("position_frd_m").text.split()], float(r.find("yaw_sign").text))
              for r in plug.findall("rotor")]
    return {"mass": g("mass_kg"), "k": g("thrust_coeff"), "ratio": g("torque_ratio_m"), "wmin": g("omega_min_rad_s"),
            "wmax": g("omega_max_rad_s"), "tau": g("motor_tau_s"), "rotors": sorted(rotors),
            "j": [float(inert.find(t).text) for t in ("ixx", "iyy", "izz")]}


def plant_lines(c):
    out = [f"plant {c['mass']!r} {c['k']!r} {c['ratio']!r} {c['wmin']!r} {c['wmax']!r} {c['tau']!r}",
           "inertia " + " ".join(repr(v) for v in c["j"])]
    out += [f"rotor {i} {p[0]!r} {p[1]!r} {p[2]!r} {s!r}" for i, p, s in c["rotors"]]
    return out


def tool_run(tool, args):
    p = subprocess.run([str(tool), *map(str, args)], capture_output=True, text=True, check=False)
    if p.returncode:
        sys.exit(f"{tool} {args}: exit {p.returncode}: {p.stderr}")


def replay(tool, s, card, work):
    log = s.run.log
    lines = [f"override {k} {t} {v}" for k, (t, v) in s.overrides.items()] + plant_lines(card)
    truths = {t["tick"]: t for t in log["truths"]}
    for t in log["ticks"]:
        w = run_l4.IMU_WORDS.unpack(t["imu"])
        lines.append(f"tick {t['tick']} {t['sil_t_us']} {w[0]:08x} {w[1]:08x} {w[2]:08x} {w[7]}")
        if t["tick"] % s.plan.att_divisor == 0:
            tr = truths[t["tick"]]
            lines.append(f"truth {t['tick']} " + " ".join(hexf(x) for x in (*tr["q_wxyz"], *tr["omega_frd"])))
    inp, out = work / "replay_in.txt", work / "replay_out.txt"
    inp.write_text("\n".join(lines) + "\n")
    tool_run(tool, ["replay", inp, out])
    text = out.read_text().splitlines()
    names = text[0].split()
    rows = [dict(zip(names, (float(v) for v in ln.split()))) for ln in text[1:]]
    bad = [r for r in rows if tuple(int(r[f"d{i}"]) for i in range(1, 5)) != tuple(log["ticks"][int(r["tick"])]["dshot"])]
    return rows, bad


def simulate(tool, s, card, work, mode, sub):
    lines = [f"override {k} {t} {v}" for k, (t, v) in s.overrides.items()] + plant_lines(card)
    lines.append(f"ticks {len(s.run.log['ticks'])}")
    inp, out = work / "sim_in.txt", work / f"sim_{mode}_{sub}.txt"
    inp.write_text("\n".join(lines) + "\n")
    tool_run(tool, ["sim", inp, mode, sub, out])
    att, rate = {}, []
    for ln in out.read_text().splitlines():
        v = ln.split()
        if v[0] == "A":
            att[int(v[1])] = ([float(x) for x in v[4:8]], [float(x) for x in v[8:11]])
        else:
            rate.append((int(v[2]), tuple(int(x) for x in v[3:7]), [float(x) for x in v[7:10]]))
    return att, rate


def series_of(att, p, count):
    out, psi0 = [], None
    for n in range(count):
        q = att[p.run_execution(n)][0]
        v, psi = t4.rotation_vector(q), t4.heading(q)
        psi0 = psi if psi0 is None else psi0
        out.append((v[0], v[1], t4.wrap(psi - psi0)))
    return out


def predicate(y, e_gz, env, k):
    """The test's predicate on trace y with the gz runs' E: (violations, worst slack, n of worst, worst outside)."""
    viol, worst = 0, (-math.inf, None, None)
    for n in range(env.count):
        for c in range(3):
            lo, hi = (env.lo[n], env.hi[n]) if c == k else (0.0, 0.0)
            out = max(lo - y[n][c], y[n][c] - hi)
            slack = out - (e_gz[n][c] + env.F)
            viol += slack > 0
            if slack > worst[0]:
                worst = (slack, n, c, out)
    return viol, worst


def window_stats(y, om, env, k, lo, hi, sp):
    """theta - sp (sp the window's tilt setpoint), the envelope's edges relative to sp, and the body rate w of the axis."""
    d = [y[n][k] - sp for n in range(lo, hi)]
    w = [om[n] for n in range(lo, hi)]
    return {"theta-sp min": min(d), "theta-sp max": max(d), "theta-sp mean": sum(d) / len(d),
            "envelope lo-sp min": min(env.lo[n] - sp for n in range(lo, hi)),
            "envelope hi-sp max": max(env.hi[n] - sp for n in range(lo, hi)),
            "w min": min(w), "w max": max(w), "theta-sp end": y[hi - 1][k] - sp}


def dshot_changes(seq):
    return sum(1 for a, b in zip(seq, seq[1:]) if a != b)


def quantum(params, card, thrust):
    """Derived values at hover (rule in the output)."""
    rows = [[params[f"mixer_m{i}_{c}"] for c in run_l4.MIXER_COLUMNS] for i in range(1, 5)]
    span_w, span_d = card["wmax"] - card["wmin"], 2047 - 48
    dw = span_w / span_d
    out = {"dw per DShot step (rad/s)": dw}
    f = [r[0] * thrust for r in rows]
    w = [math.sqrt(x / card["k"]) for x in f]
    dstar = [48 + (x - card["wmin"]) / span_w * span_d for x in w]
    out["hover per-motor thrust f_h (N)"] = f
    out["hover omega (rad/s)"] = w
    out["hover DShot (real, before rounding)"] = dstar
    d0 = [round(x) for x in dstar]
    wq = [card["wmin"] + dw * (d - 48) for d in d0]
    dT = [card["k"] * ((x + dw) ** 2 - x ** 2) for x in wq]
    out["hover DShot (rounded)"] = d0
    out["thrust per DShot step at hover dT = k((w+dw)^2 - w^2) (N)"] = dT
    r = {i: (p, s) for i, p, s in card["rotors"]}
    out["roll torque of one motor step |r_y| dT (N m)"] = [abs(r[i + 1][0][1]) * dT[i] for i in range(4)]
    out["pitch torque of one motor step |r_x| dT (N m)"] = [abs(r[i + 1][0][0]) * dT[i] for i in range(4)]
    out["yaw torque of one motor step c_q dT (N m)"] = [card["ratio"] * dT[i] for i in range(4)]
    # Request dead band: the smallest |tau| on one axis at which some motor's rounded DShot leaves its hover value.
    dd_df = [span_d / span_w / (2 * math.sqrt(card["k"] * x)) for x in f]  # d(DShot)/df at hover
    for a, name in ((1, "roll"), (2, "pitch"), (3, "yaw")):
        for sgn in (1, -1):
            need = []
            for i in range(4):
                move = sgn * rows[i][a] * dd_df[i]
                frac = dstar[i] - d0[i]
                need.append((0.5 - frac) / move if move > 0 else (-0.5 - frac) / move if move < 0 else math.inf)
            out[f"{name} request dead band, sign {sgn:+d} (N m, first-order)"] = sgn * min(need)
    return out


def fmt(x):
    if isinstance(x, float):
        return f"{x:.6g}"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(fmt(v) for v in x) + "]"
    if isinstance(x, dict):
        return "{" + ", ".join(f"{k}: {fmt(v)}" for k, v in x.items()) + "}"
    return str(x)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    tool = work / "step_cause_tool"
    subprocess.run([str(HERE / "build_tool.sh"), str(tool)], check=True)
    _, defaults = run_l5.build_parameters(run_l5.DEFAULT_PLUGIN_DIR)
    params = run_l4.read_param_defaults(defaults)
    L = ["MARV quad L5 T4 angle-mode steps: cause of the envelope excursions (decision 0006 F)",
         "command: uv run python tests/regression/quad/L05/results/step_cause/step_cause.py --work <dir> --out <file>",
         f"label: {run_l5.LABEL} (truth gyro, truth attitude, one card for truth and firmware): not a validation run",
         f"card: {CARD.relative_to(ROOT)} sha256 {sha(CARD)}",
         f"parameter table (build): {Path(defaults).relative_to(ROOT)} sha256 {sha(defaults)}",
         f"envelope: {(T3_GENERATED / 'attitude_t3_envelope.txt').relative_to(ROOT)} sha256 {sha(T3_GENERATED / 'attitude_t3_envelope.txt')}",
         f"tool: step_cause_tool.cpp sha256 {sha(HERE / 'step_cause_tool.cpp')} (built by build_tool.sh on the host-gz-l5 libraries)",
         "neutral injections (build table defaults, not overridden by the runs): " + ", ".join(
             f"{k} {params[k]!r}" for k in ("l5_chirp_axis", "l5_chirp_amp_rad_s", "l5_dist_yaw_nm")), ""]
    golden = (T3_GENERATED / "attitude_t3_golden.txt").read_text().splitlines()
    ripple = {}
    for axis in t4.AXES:
        k = t4.AXIS_INDEX[axis]
        scen = SCEN / f"step_{axis}.yaml"
        wd = work / axis
        runs, _ = run_l5.run_sequence(CARD, scen, wd, run_l5.DEFAULT_PLUGIN_DIR)
        env = t4.parse_envelope(T3_GENERATED / "attitude_t3_envelope.txt", f"step_{axis}")
        ev = t4.evaluate(runs, env, axis)
        by_m = {s.run.m: s for s in runs}
        s1, p = by_m[1], by_m[1].plan
        y1, y2 = t4.series(s1, env.count), t4.series(by_m[2], env.count)
        e_gz = [tuple(abs(u - v) for u, v in zip(r1, r2)) for r1, r2 in zip(y1, y2)]
        om_gz = [s1.executions[p.run_execution(n)]["truth"]["omega_frd"][k] for n in range(env.count)]
        card = card_of(s1.run.world_path)
        H = (env.count - 1) // 2
        a_r = 1 + H
        wins = {"hold tail": (a_r - H // 2, a_r), "release tail": (env.count - H // 2, env.count)}
        sps = {"hold tail": params["angle_tilt_max"], "release tail": 0.0}
        L += [f"== step_{axis}: scenario {scen.relative_to(ROOT)} sha256 {sha(scen)}",
              f"plan: origin a0 {p.origin}, segments {[list(x) for x in p.segments]}, end {p.end}; envelope count "
              f"{env.count}, release_execution {a_r} (H = {H}); F {env.F!r}",
              f"alignment findings (test's exact check): m1 {t4.alignment_findings(s1, p.origin)}, m2 "
              f"{t4.alignment_findings(by_m[2], by_m[2].plan.origin)}",
              f"gz predicate (test's evaluate): passed {ev['passed']}, violations {ev['violations']}, worst {fmt(ev['worst'][axis])}",
              f"gz max E over the window: {fmt([max(e[c] for e in e_gz) for c in range(3)])} (roll, pitch, heading)"]
        # 2. replay
        rows, bad = replay(tool, s1, card, wd)
        if bad or len(rows) != len(s1.run.log["ticks"]) // p.divisor + (len(s1.run.log["ticks"]) % p.divisor > 0):
            sys.exit(f"replay of step_{axis} is not bit-exact: {len(bad)} mismatches, {len(rows)} rows")
        L.append(f"replay fidelity: DShot bit-exact at all {len(rows)} rate executions of the m = 1 run; "
                 f"faults {sum(r['fault'] for r in rows)}, saturation flags set {sum(r['flag_x'] + r['flag_y'] + r['flag_z'] for r in rows)}")
        tick0 = p.tick_of(p.origin)
        for wname, (lo, hi) in wins.items():
            rr = [r for r in rows if p.tick_of(p.origin + lo) <= r["tick"] < p.tick_of(p.origin + hi)]
            ax = "xyz"[k]
            uniform = [r for r in rr if len({r['d1'], r['d2'], r['d3'], r['d4']}) == 1]
            L.append(f"replay {wname} (executions {lo}..{hi - 1}): {len(rr)} rate executions, DShot changes "
                     f"{dshot_changes([tuple(r[f'd{i}'] for i in range(1, 5)) for r in rr])}, DShot values "
                     f"{sorted({tuple(int(r[f'd{i}']) for i in range(1, 5)) for r in rr})[:8]}")
            L.append(f"  req_{ax} range [{min(r['req_' + ax] for r in rr):.4e}, {max(r['req_' + ax] for r in rr):.4e}] N m; "
                     f"quantised (static map) torque qt_{ax} values {sorted({round(r['qt_' + ax], 9) for r in rr})}; "
                     f"executions with all four DShot equal: {len(uniform)}, their max |req_{ax}| "
                     f"{max((abs(r['req_' + ax]) for r in uniform), default=0):.4e} N m; max |qt_{ax} - req_{ax}| "
                     f"{max(abs(r['qt_' + ax] - r['req_' + ax]) for r in rr):.4e} N m")
        # gz statistics
        for wname, (lo, hi) in wins.items():
            L.append(f"gz m1 {wname} (sp {sps[wname]!r}): {fmt(window_stats(y1, om_gz, env, k, lo, hi, sps[wname]))}")
        ripple[axis] = max(abs(om_gz[n]) for lo, hi in wins.values() for n in range(lo, hi))
        # gz other channels (gyroscopic coupling, off-axis)
        jv = card["j"]
        gyro = []
        for n in range(env.count):
            w = s1.executions[p.run_execution(n)]["truth"]["omega_frd"]
            jw = [jv[i] * w[i] for i in range(3)]
            gyro.append(max(abs(w[1] * jw[2] - w[2] * jw[1]), abs(w[2] * jw[0] - w[0] * jw[2]), abs(w[0] * jw[1] - w[1] * jw[0])))
        L.append(f"gz m1 largest |w x Jw| component over the window: {max(gyro):.4e} N m; largest off-axis tilt "
                 f"{max(abs(r[1 - k]) for r in y1):.4e} rad, heading {max(abs(r[2]) for r in y1):.4e} rad")
        # 3. counterfactual
        g0 = golden.index(f"scenario step_{axis}")
        gth = [float(v) for v in golden[golden.index("theta", g0) + 1: golden.index("theta", g0) + 1 + env.count]]
        gtol = float(next(x for x in golden[g0:] if x.startswith("tolerance_theta")).split()[1])
        sims = {}
        for mode in MODES:
            for sub in SUBSTEPS:
                att, rate = simulate(tool, s1, card, wd, mode, sub)
                sims[(mode, sub)] = (series_of(att, p, env.count), att, rate)
        for mode in MODES:
            y, att, rate = sims[(mode, 1)]
            y2s = sims[(mode, 2)][0]
            om = [att[p.run_execution(n)][1][k] for n in range(env.count)]
            viol, worst = predicate(y, e_gz, env, k)
            halv = max(abs(u[c] - v[c]) for u, v in zip(y, y2s) for c in range(3))
            diff = [abs(u[k] - v[k]) for u, v in zip(y, y1)]
            L.append(f"sim {mode}: predicate violations {viol}, worst slack {worst[0]:+.4e} at n {worst[1]} component "
                     f"{t4.COMPONENTS[worst[2]]} (outside {worst[3]:+.4e}); sub-step halving change {halv:.3e}; "
                     f"max |theta_sim - theta_gz| {max(diff):.4e} (n {diff.index(max(diff))}), over n < 2000 {max(diff[:2000]):.4e}")
            if mode == "design":
                L.append(f"  design control: max |theta_sim - T3 golden| {max(abs(y[n][k] - gth[n]) for n in range(env.count)):.3e} "
                         f"(T3 tolerance_theta {gtol:.3e})")
            rr = [d for (tk, d, _) in rate if tk >= tick0]
            L.append(f"  DShot changes in the window {dshot_changes(rr)}")
            for wname, (lo, hi) in wins.items():
                L.append(f"  {wname}: {fmt(window_stats(y, om, env, k, lo, hi, sps[wname]))}")
        L.append("")
    thrust = float(runs[0].overrides["l5_thrust_n"][1])
    q = quantum(params, card, thrust)
    L.append(f"== quantum at hover (derived; rule: marv_plant ESC map linear in omega over DShot 48..2047, thrust k w^2, "
             f"torque r x f and c_q f; the mixer's thrust column at the runs' l5_thrust_n {thrust!r} N)")
    L += [f"{k_}: {fmt(v)}" for k_, v in q.items()]
    kp = {ax: params[f"rate_kp_{ax}"] for ax in ("roll", "pitch")}
    for ax in ("roll", "pitch"):
        db = max(abs(q[f"{ax} request dead band, sign +1 (N m, first-order)"]), abs(q[f"{ax} request dead band, sign -1 (N m, first-order)"]))
        L.append(f"{ax}: angle error at which the proportional path alone reaches the larger dead band, "
                 f"|tau_db| / (rate_kp att_kp) = {db / (kp[ax] * params['att_kp']):.4e} rad "
                 f"(rate_kp {kp[ax]!r}, att_kp {params['att_kp']!r})")
    L += [f"L4 comparison: gz m1 largest |w| of the stepped axis in the settled tails (the quantisation's rate ripple): "
          f"{axis} {ripple[axis]:.4e} rad/s = {ripple[axis] / L4_F_RAD_S:.3f} of the L4 per-axis step F {L4_F_RAD_S} rad/s "
          "(decision 0005)" for axis in t4.AXES]
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
