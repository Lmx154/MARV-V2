#!/usr/bin/env python3
"""Cause of the L5 T4 angle-mode step excursions (decision 0006 F "T4 angle-mode steps"): a bit-exact replay of the gz runs
and a counterfactual of the T3 design model with the DShot quantisation inserted.

    uv run python tests/regression/quad/L05/results/step_cause/step_cause.py --work <scratch dir> --out <file>

Needs gz-sim 8 and the host-gz-l5 build (cmake --preset host-gz-l5 && cmake --build --preset host-gz-l5). For each axis
(roll, pitch) it:
  1. flies scenarios/quad/L05/step_<axis>.yaml at m = 2 and m = 1 with tools/sim/run_l5.py run_sequence, as
     tests/regression/quad/L05/gz/test_t4_steps.py does, and evaluates the test's own predicate (its evaluate());
  2. replays the m = 1 run's IMU samples and TRUTH records through the composition path (step_cause_tool replay) and
     refuses to report unless the replay's DShot equals the log's at every rate execution;
  3. closes the same firmware path (float, the build's libraries) around a binary64 rotational plant (step_cause_tool sim)
     in four variants: design (the T3 design plant), cont (motor-level plant, unquantised), quant (the DShot quantisation
     and marv_plant's DShot -> omega -> thrust -> torque map inserted, nothing else changed), quant_gyro (quant plus
     w x Jw); each at 1 and 2 integration sub-steps a tick (the halving check). Each variant is evaluated with the test's
     predicate (the envelope, F, and the gz runs' E) and compared with the gz trace;
  4. derives the DShot torque quantum and the request dead band at hover from the build's mixer and the card's plant map.
The gz logs and the tool's files go to --work (regenerated by a rerun: the runs are deterministic, decision 0003).
"""
