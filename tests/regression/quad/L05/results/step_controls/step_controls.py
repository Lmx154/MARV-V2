#!/usr/bin/env python3
"""The fine negative controls of the L5 T4 angle-mode steps against the widened predicate (owner decision 19: "confirm the
fine negative controls (gains x 1.1, one tick of added delay) still fail the widened T4 predicate").

    uv run python tests/regression/quad/L05/results/step_controls/step_controls.py --work <scratch dir> --out <file>

Needs gz-sim 8 and the host-gz-l5 build. The widened predicate is tests/regression/quad/L05/gz/test_t4_steps.py's evaluate():
envelope +- (E + F + Q), Q the recorded quantisation term (t3/reference/attitude_t3_q.txt). For each axis (roll, pitch):
  baseline      scenarios/quad/L05/step_<axis>.yaml flown at m = 2 and m = 1 (run_l5.run_sequence), as the test flies it;
  (a) att x 1.1 the same with att_kp overridden (sil_override) to f32(att_kp x f32(1.1)), as t3_test.cpp scales it;
  (a') rate x 1.1  rate_kp_<axis> and rate_ki_<axis> of all three axes overridden the same way;
  (b) delay     cannot be flown without a firmware change: the counterfactual of ../step_cause (step_controls_tool, the
                float firmware path around the design plant with the DShot quantisation and marv_plant's map inserted,
                variant quant, which reproduced gz within 4.9e-4 rad) with 0 and 1 tick of added delay between the rate
                loop's command and the plant (t3_test.cpp run_script's delay_ticks), at 1 and 2 integration sub-steps a
                tick, evaluated with the widened predicate and the baseline gz runs' E. The counterfactual of (a) is run
                too, as a cross-check of the surrogate against the flown (a).
Output: per case the verdict, the violations and the largest slack (distance outside the widened band; > 0 fails).
The gz logs and the tool's files go to --work (regenerated by a rerun: the runs are deterministic, decision 0003).
"""
import argparse
import hashlib
import math
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[5]
sys.path.insert(0, str(ROOT / "tools" / "sim"))
sys.path.insert(0, str(ROOT / "tools" / "card"))
sys.path.insert(0, str(ROOT / "tests" / "regression" / "quad" / "L05" / "gz"))
sys.path.insert(0, str(HERE.parent / "step_cause"))
import run_l4  # noqa: E402
import run_l5  # noqa: E402
import step_cause as sc  # noqa: E402
import test_t4_steps as t4  # noqa: E402

CARD = ROOT / "vehicles" / "uzh_neurobem_5in.yaml"
SCEN = ROOT / "scenarios" / "quad" / "L05"
T3 = ROOT / "tests" / "regression" / "quad" / "L05" / "t3" / "reference"
GAIN_SCALE = 1.1  # scenario test value: the spec's fine control, "gain x 1.1" (decision 0006 F; t3_test.cpp kGainScale)
DELAYS = (0, 1)  # ticks of added delay: 0 (the surrogate itself) and 1 (the spec's fine control)
SUBSTEPS = (1, 2)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def scaled(value):
    return repr(run_l4.r32(value * run_l4.r32(GAIN_SCALE)))


def widened(y, e_gz, env, k):
    """test_t4_steps.evaluate's predicate on a trace y with the gz runs' E: (violations, max slack, n, component, outside)."""
    viol, worst = 0, (-math.inf, None, None, None)
    for n in range(env.count):
        for c in range(3):
            lo, hi = (env.lo[n], env.hi[n]) if c == k else (0.0, 0.0)
            out = max(lo - y[n][c], y[n][c] - hi)
            slack = out - (e_gz[n][c] + env.F + (env.Q if c == k else 0.0))
            viol += slack > 0
            if slack > worst[0]:
                worst = (slack, n, t4.COMPONENTS[c], out)
    return viol, worst


def gz_line(label, ev):
    w = max(ev["worst"].values(), key=lambda x: x["slack"])
    return (f"{label}: {'PASS' if ev['passed'] else 'FAIL'}, violations {ev['violations']}, max slack {w['slack']:+.4e} "
            f"at n {w['n']} (outside {w['outside']:+.4e}, E {w['E']:.3e}), per component "
            + "; ".join(f"{c} max outside {ev['components'][c]['max_out']:+.4e} viol {ev['components'][c]['violations']}"
                        for c in t4.COMPONENTS) + f", stale {ev['stale_reads_in_window']}")


def simulate(tool, s, card, work, mode, sub, delay, tag):
    lines = [f"override {k} {t} {v}" for k, (t, v) in s.overrides.items()] + sc.plant_lines(card)
    lines.append(f"ticks {len(s.run.log['ticks'])}")
    inp, out = work / f"sim_in_{tag}.txt", work / f"sim_{tag}_{mode}_{sub}_{delay}.txt"
    inp.write_text("\n".join(lines) + "\n")
    p = subprocess.run([str(tool), "sim", str(inp), mode, str(sub), str(delay), str(out)], capture_output=True, text=True,
                       check=False)
    if p.returncode:
        sys.exit(f"{tool}: exit {p.returncode}: {p.stderr}")
    att = {}
    for ln in out.read_text().splitlines():
        v = ln.split()
        if v[0] == "A":
            att[int(v[1])] = ([float(x) for x in v[4:8]], [float(x) for x in v[8:11]])
    return att


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    tool = work / "step_controls_tool"
    subprocess.run([str(HERE / "build_tool.sh"), str(tool)], check=True)
    _, defaults = run_l5.build_parameters(run_l5.DEFAULT_PLUGIN_DIR)
    params = run_l4.read_param_defaults(defaults)
    att_over = {"att_kp": (run_l5.F32, scaled(params["att_kp"]))}
    rate_over = {f"rate_{g}_{x}": (run_l5.F32, scaled(params[f"rate_{g}_{x}"])) for g in ("kp", "ki")
                 for x in ("roll", "pitch", "yaw")}
    L = ["MARV quad L5 T4 angle-mode steps: fine negative controls against the widened predicate (owner decision 19)",
         "command: uv run python tests/regression/quad/L05/results/step_controls/step_controls.py --work <dir> --out <file>",
         f"label: {run_l5.LABEL}: not a validation run",
         f"card: {CARD.relative_to(ROOT)} sha256 {sha(CARD)}",
         f"parameter table (build): {Path(defaults).relative_to(ROOT)} sha256 {sha(defaults)}",
         f"envelope sha256 {sha(T3 / 'attitude_t3_envelope.txt')}; Q file sha256 {sha(T3 / 'attitude_t3_q.txt')}",
         f"predicate: tests/regression/quad/L05/gz/test_t4_steps.py sha256 {sha(t4.__file__)} (evaluate)",
         f"tool: step_controls_tool.cpp sha256 {sha(HERE / 'step_controls_tool.cpp')}",
         f"gain scale {GAIN_SCALE} (f32 {run_l4.r32(GAIN_SCALE)!r}); att override {att_over}; rate overrides {rate_over}", ""]
    for axis in t4.AXES:
        k = t4.AXIS_INDEX[axis]
        env = t4.parse_envelope(T3 / "attitude_t3_envelope.txt", f"step_{axis}")
        L.append(f"== step_{axis}: F {env.F!r}, Q (theta) {env.Q!r}, F + Q {env.F + env.Q!r}")
        seqs = {}
        for name, tag, over in (("baseline", "base", None), ("(a) att_kp x 1.1", "att", att_over),
                                ("(a') rate kp, ki x 1.1", "rate", rate_over)):
            runs, _ = run_l5.run_sequence(CARD, SCEN / f"step_{axis}.yaml", work / axis / tag, run_l5.DEFAULT_PLUGIN_DIR,
                                          overrides=over)
            seqs[name] = runs
            L.append("gz " + gz_line(name, t4.evaluate(runs, env, axis)))
        base = {s.run.m: s for s in seqs["baseline"]}
        y1, y2 = t4.series(base[1], env.count), t4.series(base[2], env.count)
        e_gz = [tuple(abs(u - v) for u, v in zip(r1, r2)) for r1, r2 in zip(y1, y2)]
        card = sc.card_of(base[1].run.world_path)
        cases = [("quant", d, "base", base[1]) for d in DELAYS] + [("design", d, "base", base[1]) for d in DELAYS]
        cases.append(("quant", 0, "att11", {s.run.m: s for s in seqs["(a) att_kp x 1.1"]}[1]))
        first = {}
        for mode, delay, tag, s in cases:
            res = []
            for sub in SUBSTEPS:
                att = simulate(tool, s, card, work / axis, mode, sub, delay, tag)
                res.append(sc.series_of(att, s.plan, env.count))
            viol, worst = widened(res[0], e_gz, env, k)
            halv = max(abs(u[c] - v[c]) for u, v in zip(*res) for c in range(3))
            dgz = max(abs(u[k] - v[k]) for u, v in zip(res[0], y1))
            stepped = max(max(env.lo[n] - res[0][n][k], res[0][n][k] - env.hi[n]) - (e_gz[n][k] + env.F + env.Q)
                          for n in range(env.count))
            first.setdefault((mode, tag), res[0])
            moved = max(abs(u[k] - v[k]) for u, v in zip(res[0], first[(mode, tag)]))
            L.append(f"counterfactual {mode} delay {delay} ({'att_kp x 1.1' if tag == 'att11' else 'live gains'}): "
                     f"{'FAIL' if viol else 'PASS'}, violations {viol}, max slack {worst[0]:+.4e} at n {worst[1]} "
                     f"{worst[2]} (outside {worst[3]:+.4e}); stepped component max slack {stepped:+.4e}; sub-step "
                     f"halving change {halv:.3e}; max |theta - theta_gz baseline| {dgz:.4e}; max |theta - theta at delay "
                     f"0| {moved:.4e}")
        L.append("")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
