"""Cause of the L5 T4 large-angle recovery results (decision 0006 C, F "T4 large-angle recovery"; owner decisions 5, 15 and 23)
on the final scenarios: R1 (recover_inverted, roll pi - 0.01) and R2 (recover_tumble, inverted at rate_max on all axes), both
with the rotors at the hover speed (initial_state.rotor_speed_rad_s: hover, decision 0007).

    uv run python tests/regression/quad/L05/results/recovery_cause/recovery_cause.py --work <scratch dir> --out <file>

Needs gz-sim 8 and the host-gz-l5 build. It flies both scenarios at m = 2 and m = 1 with tools/sim/run_l5.py run_sequence (as
tests/regression/quad/L05/gz/test_t4_recovery.py does; its execution n is the run's attitude execution n from tick 0), replays
each m = 1 run through the composition path with recovery_cause_tool (refusing to report unless every DShot command is
reproduced bit for bit), runs the counterfactual ladder of the same float firmware path around binary64 plants
(recovery_cause_tool sim: design; cont = allocation, motor lag and rotor map, unquantised; quant = plus the DShot rounding;
_gyro = plus -w x Jw; the rotors start at the world's initial_rotor_speed_rad_s, as the plant does), and compares the R1
counterfactual with gz against the test's own E + F + Q (test_t4_recovery.py make_design and its predicate's terms).
The gz logs and the tool's files go to --work (regenerated by a rerun: the runs are deterministic, decision 0003).
"""
