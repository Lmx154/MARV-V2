def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def alpha(q):
    """Tilt angle: the angle between body z and NED down, 2 asin(sqrt(x^2 + y^2)) of the unit quaternion."""
    n = math.sqrt(sum(c * c for c in q))
    return 2.0 * math.asin(min(1.0, math.sqrt((q[1] / n) ** 2 + (q[2] / n) ** 2)))


def alpha_of_err(v):
    """alpha from the rotation vector v of the level error (recovery_model.channels err_x, err_y, err_z)."""
    th = math.sqrt(sum(c * c for c in v))
    if th == 0:
        return 0.0
    s = math.sin(th / 2) / th
    return 2.0 * math.asin(min(1.0, math.hypot(v[0] * s, v[1] * s)))


def first_below(seq, bound):
    return next((n for n, x in enumerate(seq) if x < bound), None)


def euler_step(q, w, j, h, sub=64):
    """Torque-free rigid body: J w' = -w x J w, q' = q (x) (0, w) / 2, RK4 in `sub` sub-steps over h."""
    def f(qq, ww):
        jw = [j[i] * ww[i] for i in range(3)]
        c = (ww[1] * jw[2] - ww[2] * jw[1], ww[2] * jw[0] - ww[0] * jw[2], ww[0] * jw[1] - ww[1] * jw[0])
        dw = [-c[i] / j[i] for i in range(3)]
        dq = rm.oracle.qmul(qq, (0.0, *ww))
        return [0.5 * x for x in dq], dw
    hs = h / sub
    for _ in range(sub):
        k1 = f(q, w)
        k2 = f([a + hs / 2 * b for a, b in zip(q, k1[0])], [a + hs / 2 * b for a, b in zip(w, k1[1])])
        k3 = f([a + hs / 2 * b for a, b in zip(q, k2[0])], [a + hs / 2 * b for a, b in zip(w, k2[1])])
        k4 = f([a + hs * b for a, b in zip(q, k3[0])], [a + hs * b for a, b in zip(w, k3[1])])
        q = [a + hs / 6 * (b + 2 * c + 2 * d + e) for a, b, c, d, e in zip(q, k1[0], k2[0], k3[0], k4[0])]
        w = [a + hs / 6 * (b + 2 * c + 2 * d + e) for a, b, c, d, e in zip(w, k1[1], k2[1], k3[1], k4[1])]
    n = math.sqrt(sum(c * c for c in q))
    return [c / n for c in q], w


def qdist(a, b):
    d = abs(sum(x * y for x, y in zip(a, b)))
    return 2.0 * math.acos(min(1.0, d))


def run_tool(tool, args):
    p = subprocess.run([str(tool), *map(str, args)], capture_output=True, text=True, check=False)
    if p.returncode:
        sys.exit(f"{tool} {args}: exit {p.returncode}: {p.stderr}")


def world_rotors(s):
    """The initial rotor speeds the world passes to marv_plant (initial_rotor_speed_rad_s), as text."""
    import xml.etree.ElementTree as ET  # noqa: PLC0415
    e = ET.parse(s.run.world_path).getroot().find(".//plugin[@name='marv::gz::Lockstep']/initial_rotor_speed_rad_s")
    return e.text.strip() if e is not None else "rest"


def sim(tool, s, card, work, mode, rotors, q0, w0, first_zero=1, set_state=None):
    lines = [f"override {k} {t} {v}" for k, (t, v) in s.overrides.items()] + sc.plant_lines(card)
    lines += [f"ticks {len(s.run.log['ticks'])}", "init " + " ".join(repr(float(x)) for x in (*q0, *w0)),
              f"rotors {rotors}", f"first_read_zero {first_zero}"]
    if set_state:
        lines.append(f"set_state {set_state[0]} " + " ".join(repr(float(x)) for x in set_state[1]))
    inp, out = work / "sim_in.txt", work / f"sim_{mode}.txt"
    inp.write_text("\n".join(lines) + "\n")
    run_tool(tool, ["sim", inp, mode, 1, out])
    att, rate = [], []
    for ln in out.read_text().splitlines():
        v = ln.split()
        if v[0] == "A":
            att.append(([float(x) for x in v[4:8]], [float(x) for x in v[8:11]]))
        else:
            rate.append([int(x) for x in v[1:7]] + [float(x) for x in v[7:13]] + [int(x) for x in v[13:16]])
    return att, rate


def truth_series(s):
    return [(list(x["truth"]["q_wxyz"]), list(x["truth"]["omega_frd"])) for x in s.executions]


def summary(att, n_end, t_a):
    al = [alpha(q) for q, _ in att[:n_end]]
    last_q, last_w = att[n_end - 1]
    ch = rm.channels(last_q, last_w)
    n90, n10 = first_below(al, math.pi / 2), first_below(al, TENTH_PI)
    return {"alpha<90deg at exec": n90, "(s)": n90 * t_a if n90 is not None else None, "alpha<0.1pi at exec": n10,
            "(s) ": n10 * t_a if n10 is not None else None,
            "alpha max after exec 1": max(al[1:]), "final alpha": al[-1], "final heading err (err_z)": ch[2],
            "final |w|": math.sqrt(sum(c * c for c in last_w)), "max |w|": max(math.sqrt(sum(c * c for c in w)) for _, w in att[:n_end])}


def fmt(x):
    if isinstance(x, float):
        return f"{x:.5g}"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(fmt(v) for v in x) + "]"
    if isinstance(x, dict):
        return "{" + ", ".join(f"{k}: {fmt(v)}" for k, v in x.items()) + "}"
    return str(x)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    tool = work / "recovery_cause_tool"
    subprocess.run([str(HERE / "build_tool.sh"), str(tool)], check=True)
    _, defaults = run_l5.build_parameters(run_l5.DEFAULT_PLUGIN_DIR)
    params = run_l4.read_param_defaults(defaults)
    L = ["MARV quad L5 T4 large-angle recovery: cause file on the final scenarios (decision 0006 C, F; owner decisions 5, 15, 23)",
         "command: uv run python tests/regression/quad/L05/results/recovery_cause/recovery_cause.py --work <dir> --out <file>",
         f"label: {run_l5.LABEL}: not a validation run",
         f"card: {CARD.relative_to(ROOT)} sha256 {sha(CARD)}",
         f"parameter table (build): {Path(defaults).relative_to(ROOT)} sha256 {sha(defaults)}",
         f"scenarios: {R1} sha256 {sha(SCEN / (R1 + '.yaml'))}, {R2} sha256 {sha(SCEN / (R2 + '.yaml'))}",
         f"tool: recovery_cause_tool.cpp sha256 {sha(HERE / 'recovery_cause_tool.cpp')}; design model: recovery_model.py sha256 "
         f"{sha(rm.__file__)}; test: test_t4_recovery.py sha256 {sha(t4r.__file__)}", ""]
    recorded = t4r.recorded_inputs()
    su = rm.oracle.Setup(recorded)
    rows = [[params[f"mixer_m{i}_{c}"] for c in run_l4.MIXER_COLUMNS] for i in range(1, 5)]
    kq = params["rotor_thrust_coeff"]
    f_min, f_max = kq * params["idle_speed"] ** 2, kq * params["rotor_speed_max"] ** 2
    runs = {}
    for name in (R1, R2):
        seq, _ = run_l5.run_sequence(CARD, SCEN / f"{name}.yaml", work / name, run_l5.DEFAULT_PLUGIN_DIR)
        runs[name] = {s.run.m: s for s in seq}
    s1 = runs[R2][1]
    card = sc.card_of(s1.run.world_path)
    J = card["j"]
    thrust = float(s1.overrides["l5_thrust_n"][1])
    held = [run_l4.tau_held(rows, c, thrust, f_min, f_max) for c in (1, 2, 3)]
    ta, adiv = float(s1.plan.period_s), s1.plan.att_divisor
    L.append(f"attitude period T_a {ta!r} s ({adiv} ticks); rate period {float(s1.plan.tick_s) * s1.plan.divisor!r} s")

    # ---- 1. initial state in gz (R2)
    st = l5s.values(l5s.load(SCEN / f"{R2}.yaml"))["initial_state"]
    q0, w0 = st["attitude_q_wxyz"], st["body_rates_frd_rad_s"]
    L.append(f"== 1. R2 initial state in gz (scenario q0 {q0}, w0 {w0}; world initial_rotor_speed_rad_s {world_rotors(s1)})")
    for m in (2, 1):
        s = runs[R2][m]
        log = s.run.log
        L.append(f"m = {m}:")
        for i, stp in enumerate(log["steps"][:2]):
            L.append(f"  host step {i} (ticks {i * m}..{i * m + m - 1}) read: body_q {fmt(list(stp['body_q_wxyz']))}, "
                     f"body_omega {fmt(list(stp['body_omega_frd']))}")
        for t in log["ticks"][:m + 1]:
            g = run_l4.IMU.unpack(t["imu"])[:3]
            L.append(f"  tick {t['tick']}: gyro to SIL {fmt(list(g))}, DShot {t['dshot']}, rotor speed {fmt(list(t['rotor_speed']))}")
        qp, wp = euler_step(list(q0), list(w0), J, m * float(s.plan.tick_s))
        stp = log["steps"][1]
        L.append(f"  host step 1 read vs the torque-free rigid body from (q0, w0) at t = 0 over {m} tick(s): |dq| "
                 f"{qdist(qp, stp['body_q_wxyz']):.3e} rad, max |dw| {max(abs(x - y) for x, y in zip(wp, stp['body_omega_frd'])):.3e} rad/s")

    # ---- 2. R2 cause
    L.append("")
    L.append("== 2. R2 cause (m = 1 replay)")
    L.append(f"collective-held torque envelope tau_held (run_l4.tau_held at l5_thrust_n {thrust!r} N): {fmt(held)} N m (roll, pitch, yaw)")
    rr, bad = replay_rows(tool, s1, card, work / R2)
    if bad:
        sys.exit(f"R2 replay is not bit-exact: {len(bad)} mismatches")
    L.append(f"replay fidelity: DShot bit-exact at all {len(rr)} rate executions")
    for ax in "xyz":
        f = [r["k"] for r in rr if r[f"flag_{ax}"]]
        L.append(f"flag_{ax}: set at {len(f)} executions" + (f", first k {int(f[0])} (t {rr[int(f[0])]['t_us'] / 1e6:.4f} s), last k "
                                                            f"{int(f[-1])} (t {rr[int(f[-1])]['t_us'] / 1e6:.4f} s)" if f else ""))
    ratios = []
    for r in rr:
        s_ = r["ach_x"] / r["req_x"] if r["req_x"] else (r["ach_y"] / r["req_y"] if r["req_y"] else 1.0)
        t_ = r["ach_z"] / r["req_z"] if r["req_z"] else 1.0
        ratios.append((s_, t_))
    below = [k for k, (x, y) in enumerate(ratios) if x < 1 - 1e-6 or y < 1 - 1e-6]
    L.append(f"s or t < 1: {len(below)} executions" + (f", first k {below[0]}, last k {below[-1]} (t {rr[below[-1]]['t_us'] / 1e6:.4f} s), "
                                                      f"min s {min(x for x, _ in ratios):.4f}, min t {min(y for _, y in ratios):.4f}" if below else ""))
    kp = [params[f"rate_kp_{x}"] for x in ("roll", "pitch", "yaw")]
    imu = [run_l4.IMU.unpack(t["imu"])[:3] for t in s1.run.log["ticks"]]
    integ = [[r[f"req_{ax}"] - kp[i] * (r[f"sp_{ax}"] - imu[int(r["tick"])][i]) for i, ax in enumerate("xyz")] for r in rr]
    gyro = []
    for x in s1.executions:
        w = x["truth"]["omega_frd"]
        jw = [J[i] * w[i] for i in range(3)]
        gyro.append([w[1] * jw[2] - w[2] * jw[1], w[2] * jw[0] - w[0] * jw[2], w[0] * jw[1] - w[1] * jw[0]])
    L.append(f"|w x Jw| max per axis over the run: {fmt([max(abs(g[i]) for g in gyro) for i in range(3)])} N m; at execution 1: "
             f"{fmt(gyro[1])} N m; ratio to tau_held at execution 1: {fmt([abs(gyro[1][i]) / held[i] for i in range(3)])}")
    L.append(f"max |achieved torque| per axis: {fmt([max(abs(r['ach_' + ax]) for r in rr) for ax in 'xyz'])} N m; "
             f"max |request| per axis: {fmt([max(abs(r['req_' + ax]) for r in rr) for ax in 'xyz'])} N m")
    L.append(f"integrator (req - kp (sp - gyro)) max |I| per axis: {fmt([max(abs(i[c]) for i in integ) for c in range(3)])} N m; "
             f"at k = 100, 400, 1600, 8000: {fmt([integ[k] for k in (100, 400, 1600, 8000) if k < len(integ)])}")
    n_end = len(s1.executions)
    tr = truth_series(s1)
    L.append(f"gz m = 1 recovery: {fmt(summary(tr, n_end, ta))}; final q {fmt(tr[-1][0])}, final w {fmt(tr[-1][1])}")
    for k in (1, 16, 80, 160, 400, 800, 1600):
        q, w = tr[k]
        L.append(f"  exec {k} (t {k * ta:.4f} s): alpha {alpha(q):.4f}, err {fmt(list(rm.channels(q, w)[:3]))}, w {fmt(w)}, "
                 f"|w x Jw| {fmt(gyro[k])}")
    nom, _ = rm.member_run(su, 0.0, 0.0, tuple(q0), tuple(w0), n_end)
    L.append("counterfactual ladder (float firmware path; tick 0 reads w = 0 as gz; rotors at the world's initial speeds): the largest "
             "channel distance to the gz m = 1 trace and to the nominal design member of recovery_model.py (no w x Jw, no "
             "saturation), executions >= 1:")
    rot = world_rotors(s1)
    for mode in LADDER:
        att, rate = sim(tool, s1, card, work / R2, mode, rot, q0, w0)
        dgz = max(max(abs(a - b) for a, b in zip(rm.channels(*x), rm.channels(*y))) for x, y in zip(att[1:], tr[1:]))
        dnom = max(max(abs(a - b) for a, b in zip(rm.channels(*x), y)) for x, y in zip(att[1:], nom[1:]))
        sat = sum(1 for r in rate if r[12] or r[13] or r[14])
        L.append(f"  {mode:<10}: |sim - gz| {dgz:.4e}, |sim - design nominal| {dnom:.4e}, saturated rate executions {sat}; "
                 f"{fmt(summary(att, n_end, ta))}")
    dnom_gz = max(max(abs(a - b) for a, b in zip(rm.channels(*x), y)) for x, y in zip(tr[1:], nom[1:]))
    L.append(f"  gz m = 1 against the design nominal: {dnom_gz:.4e}; design nominal {fmt(summary([(_q_of(c), c[3:]) for c in nom], n_end, ta))}")

    # ---- 3. R1
    s = runs[R1][1]
    rr1, bad1 = replay_rows(tool, s, card, work / R1)
    if bad1:
        sys.exit(f"R1 replay is not bit-exact: {len(bad1)} mismatches")
    L.append("")
    L.append(f"== 3. R1 (replay: DShot bit-exact at all {len(rr1)} rate executions of the m = 1 run)")
    stn = l5s.values(l5s.load(SCEN / f"{R1}.yaml"))["initial_state"]
    w_yaw, k_att = params["att_yaw_weight"], params["att_kp"]
    for e in (0, 1):
        q = list(s.executions[e]["truth"]["q_wxyz"])
        row = next(r for r in rr1 if int(r["tick"]) == adiv * e)
        qe = rm.canonical((q[0], -q[1], -q[2], -q[3]))
        rho = math.hypot(qe[0], qe[3])
        aa = (qe[0] * qe[1] - qe[2] * qe[3]) / rho
        bb = (qe[0] * qe[2] + qe[1] * qe[3]) / rho
        L.append(f"exec {e}: truth q {fmt(q)}, rho {rho:.4e}, split tilt axis ({aa:.4f}, {bb:.4f}), rate setpoint "
                 f"{fmt([row['sp_x'], row['sp_y'], row['sp_z']])}")
    tr1 = truth_series(s)
    n1 = len(tr1)
    L.append(f"gz m = 1 recovery: {fmt(summary(tr1, n1, ta))}; final q {fmt(tr1[-1][0])}")
    live = {k: params[k] for k in recorded if k in params}
    d = t4r.make_design(R1, live)
    ev = t4r.evaluate([runs[R1][2], runs[R1][1]], d)
    L.append(f"test predicate on gz (test_t4_recovery.evaluate): passed {ev['passed']}, violations {ev['violations']}; F {fmt(d.F)}; "
             f"Q {fmt(d.Q)}")
    y1 = t4r.series(runs[R1][1], d.count)
    y2 = t4r.series(runs[R1][2], d.count)
    att, _ = sim(tool, s, card, work / R1, "quant_gyro", world_rotors(s), stn["attitude_q_wxyz"], stn["body_rates_frd_rad_s"])
    ys = [rm.channels(q, w) for q, w in att[:d.count]]
    worst = []
    for c, ch in enumerate(rm.CHANNELS):
        best = (-math.inf, None, None)
        for n in range(d.count):
            if n == 0 and ch.startswith("w_"):
                continue
            diff = abs(ys[n][c] - y1[n][c])
            slack = diff - (abs(y1[n][c] - y2[n][c]) + d.F[c] + d.Q[c])
            if slack > best[0]:
                best = (slack, n, diff)
        worst.append(f"{ch} max |sim - gz| {max(abs(ys[n][c] - y1[n][c]) for n in range(1, d.count)):.3e}, worst slack "
                     f"{best[0]:+.3e} at exec {best[1]}")
    L.append("counterfactual quant_gyro (rotors at the world's initial speeds) against gz m = 1, within E + F + Q per channel "
             "(slack <= 0 inside): " + "; ".join(worst))
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


def _q_of(c):
    v = c[:3]
    th = math.sqrt(sum(x * x for x in v))
    if th == 0:
        return [1.0, 0.0, 0.0, 0.0]
    s = math.sin(th / 2) / th
    e = [math.cos(th / 2), v[0] * s, v[1] * s, v[2] * s]
    return [e[0], -e[1], -e[2], -e[3]]  # the level error is conj(q): q = conj(error)


def replay_rows(tool, s, card, work):
    work.mkdir(parents=True, exist_ok=True)
    return sc.replay(tool, s, card, work)


if __name__ == "__main__":
    main()
