def _q_of(c):
    v = c[:3]
    th = math.sqrt(sum(x * x for x in v))
    if th == 0:
        return [1.0, 0.0, 0.0, 0.0]
    s = math.sin(th / 2) / th
    e = [math.cos(th / 2), v[0] * s, v[1] * s, v[2] * s]
    return [e[0], -e[1], -e[2], -e[3]]  # the level error is conj(q): q = conj(error)


