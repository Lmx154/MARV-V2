def _max_abs_diff(a, b):
    return max(abs(x - y) for x, y in zip(a, b))


def _tick_rule(x, divisor):
    return max(abs(x[k + 1] - x[k]) for k in range(len(x) - 1)) / divisor


def _rest_speeds(plant, thrust):
    """The rotor speeds of the zero-torque allocation of the thrust request (simulate's mixer: f_i = c M[i, thrust])."""
    return [math.sqrt(thrust * row[0] / plant.k) for row in plant.m]


