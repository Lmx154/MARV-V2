def _l5_design(ctx, s=0.0, t=0.0):
    p, su = ctx["p5"], ctx["su"]
    return bd.DesignPlant(tuple(j * (1 + s * su.j_band) for j in ctx["j5"]), p["motor_tau"] * (1 + t * su.tau_band))


def _lpf(su):
    return fe.Sensor("the L5 oracle's chain low-pass", 0, (su.lpf,))


@pytest.mark.parametrize("scenario", ["recover_tumble", "recover_inverted"])
def test_l5_design_mode_is_recovery_model_bit_for_bit(ctx, scenario):
    su = ctx["su"]
    st = fe.schema.load_yaml(ROOT / "scenarios" / "quad" / "L05" / f"{scenario}.yaml")["initial_state"]
    q0, w0 = tuple(st["attitude_q_wxyz"]["value"]), tuple(st["body_rates_frd_rad_s"]["value"])
