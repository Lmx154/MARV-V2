@pytest.mark.parametrize("name, segment", [("step_roll", STEP_SEGMENT), ("yaw_release", YAW_SEGMENT)])
def test_l5_design_mode_is_the_t3_golden_bit_for_bit(ctx, name, segment):
    su = ctx["su"]
    gold = aor.simulate(su, name, segment)
    n_att = su.attitude_executions(segment)
    axis = aor.scenario_axis(name)
    sticks = tuple(aor.script_sticks(name, a, 1, 1 + segment) for a in range(n_att))
    for law in (bd.oracle_rate, None):
        res = bd.run(bd.l5_law(ctx["p5"]), _lpf(su), _l5_design(ctx), bd.l5_plan(su, n_att * su.ratio, 0.0), 0.0,
                     attitude=bd.Attitude(su.cfg, su.ratio, sticks, law))
        assert res["phi"][axis][::su.ratio] == gold["th"] and res["w"][axis][::su.ratio] == gold["om"], law
        if name == "yaw_release":
            assert gold["lock_a"] is not None
