def _shifted(sps, bias):
    return [[x - b if k > 0 else x for k, x in enumerate(col)] for col, b in zip(sps, bias)]


def test_l4_bias_is_a_setpoint_offset_bit_for_bit_and_ff_breaks_it(ctx, capsys):
    c, step, sps = ctx["c"], ctx["step"], ctx["sps"]
    sensor, plant = c["sensors"]["T4e"], c["plants"][0]
    bias = bd.gyro_bias(GYRO_CORNER)
    out = {}
    for name in ("PID", "PID+FF+lag"):
        law = c["laws"][name]
        biased, _ = fe.simulate(law, sensor, plant, step, sps, step.thrust_n, bias=bias)
        offset, _ = fe.simulate(law, sensor, plant, step, _shifted(sps, bias), step.thrust_n)
        out[name] = (biased == offset, max(_max_abs_diff(x, y) for x, y in zip(biased, offset)))
    _say(capsys, f"(5 a) L4 step_roll, simulate(bias b) - simulate(setpoints - b): FF off max {out['PID'][1]:.3e}, "
                 f"FF on max {out['PID+FF+lag'][1]:.3e} rad/s")
    assert out["PID"][0]
    assert not out["PID+FF+lag"][0]


def test_l4_hold_delta_is_minus_b_s_within_one_tick(ctx, capsys):
    c, step = ctx["c"], ctx["step"]
    p = c["fixture"]
    law, sensor = c["laws"]["PID"], c["sensors"]["T4e"].linear
    plant = dataclasses.replace(c["plants"][0], inertia=tuple(p[k] for k in fe.INERTIA_KEYS), tau=p["motor_tau"],
                                coupling=False)
    n = step.end_execution + 1
    hold = [[0.0] * n for _ in range(3)]
    bias = bd.gyro_bias(GYRO_CORNER)
    kw = {"setpoints": hold, "rotor0": _rest_speeds(plant, step.thrust_n), "dshot": bd.DSHOT_OFF}
    biased = bd.run(law, sensor, plant, step, step.thrust_n, bias=bias, **kw)["w"]
    nominal = bd.run(law, sensor, plant, step, step.thrust_n, bias=(0.0, 0.0, 0.0), **kw)["w"]
    stamps = [step.stamp_us(k) for k in range(n)]
    lines = []
    def minus_b_s(a, j_scale):
        jt, tt = p[fe.INERTIA_KEYS[a]] * j_scale, p["motor_tau"]
        maps = (c["su"].plant_map(jt, tt), fe.tick_map(c["su1"], jt, tt))
        s = fe.linear_response(law.kp[a], law.ki[a], law.kd[a], law.tau_ref[a], law.d_tau[a], sensor, maps,
                               [0.0] + [1.0] * (n - 1), stamps, step.divisor)
        return [-bias[a] * x for x in s]

    for a in range(3):
        lin, planted = minus_b_s(a, 1.0), minus_b_s(a, FINE_FACTOR)
        delta = [x - y for x, y in zip(biased[a], nominal[a])]
        diff, rule = _max_abs_diff(delta, lin), _tick_rule(lin, step.divisor)
        ctl, ctl_rule = _max_abs_diff(delta, planted), _tick_rule(planted, step.divisor)
        lines.append(f"(5 b) L4 hold, axis {fe.AXES[a]}: max |delta - (-b s)| {diff:.3e} rad/s ({diff / abs(bias[a]):.2e} "
                     f"of |b|), one-tick rule {rule:.3e}; control J x {FINE_FACTOR}: {ctl:.3e} against {ctl_rule:.3e}")
        assert max(abs(x) for x in nominal[a]) == 0.0
        assert diff <= rule, a
        assert ctl > ctl_rule, a
    _say(capsys, *lines)


