def test_l4_mode_is_simulate_bit_for_bit(ctx):
    c = ctx["c"]
    law, sensor, plant, plan, sps = c["laws"]["PID+FF+lag"], c["sensors"]["T4e"], c["plants"][0], c["plan"], c["sps"]
    bias = bd.gyro_bias(GYRO_CORNER)
    e = bd.clock_error(1, ctx["doc"])
    n = plan.end_execution + 1
    torque = [[0.0] * n, [TEST_TORQUE_NM if k % 2 else -TEST_TORQUE_NM for k in range(n)], [0.0] * n]
    runs = []
    for kw in ({}, {"bias": bias, "clock_error": e, "torque": torque}):
        w, flagged = fe.simulate(law, sensor, plant, plan, sps, plan.thrust_n, **kw)
        res = bd.run(law, sensor, plant, plan, plan.thrust_n, setpoints=sps, **kw)
        assert res["w"] == w and res["flagged"] == flagged, sorted(kw)
        runs.append(w)
    assert runs[1] != runs[0]


