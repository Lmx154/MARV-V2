def _hold(ctx, n):
    su = ctx["su"]
    return bd.Attitude(su.cfg, su.ratio, ((0.0, 0.0, 0.0),) * n), bd.l5_plan(su, n * su.ratio, ctx["step"].thrust_n)


def _ff_law(ctx):
    ffl = ctx["c"]["laws"]["PID+FF+lag"]
    return bd.l5_law(ctx["p5"], ff=(ctx["j5"], ctx["p5"]["motor_tau"], ffl.ff_tau))


def test_l5_bias_is_a_rate_reference_offset_bit_for_bit_and_ff_breaks_it(ctx, capsys):
    su, plant, sensor = ctx["su"], ctx["plant5"], ctx["c"]["sensors"]["T4e"]
    n = L5_IDENTITY_EXECUTIONS
    sticks = tuple(aor.script_sticks("step_roll", a, 1, 1 + L5_STEP_SEGMENT) for a in range(n))
    att, plan = bd.Attitude(su.cfg, su.ratio, sticks), bd.l5_plan(su, n * su.ratio, ctx["step"].thrust_n)
    bias = bd.gyro_bias(GYRO_CORNER)
    offset = [[0.0] + [-b] * (n * su.ratio - 1) for b in bias]
    rotor0 = _rest_speeds(plant, plan.thrust_n)
    out = {}
    for name, law in (("FF off", bd.l5_law(ctx["p5"])), ("FF on", _ff_law(ctx))):
        a = bd.run(law, sensor, plant, plan, plan.thrust_n, attitude=att, rotor0=rotor0, bias=bias)
        b = bd.run(law, sensor, plant, plan, plan.thrust_n, attitude=att, rotor0=rotor0, rate_add=offset)
        out[name] = (a["w"] == b["w"] and a["q"] == b["q"], max(_max_abs_diff(x, y) for x, y in zip(a["w"], b["w"])))
    _say(capsys, f"(6 a) L5 step_roll, run(bias b) - run(rate_add -b), w: FF off max {out['FF off'][1]:.3e}, FF on max "
                 f"{out['FF on'][1]:.3e} rad/s")
    assert out["FF off"][0]
    assert not out["FF on"][0]


def offset_bound(r_end, b, kp):
    """|e_end - b / kp| for the single-axis law r = 2 kp sin(e / 2) (its yaw form has the smaller cubic): e_end =
    2 asin(r_end / (2 kp)), so the bound is |r_end - b| / (kp sqrt(1 - xi^2)) with xi = max(|r_end|, |b|) / (2 kp) (the mean
    value theorem) plus |2 asin(b / (2 kp)) - b / kp| <= |b / kp|^3 / 24 (1 - xi^2)^(-3/2) (Taylor's remainder)."""
    xi = max(abs(r_end), abs(b)) / (2 * kp)
    return abs(r_end - b) / (kp * math.sqrt(1 - xi * xi)) + abs(b / kp) ** 3 / TAYLOR_DIVISOR / (1 - xi * xi) ** 1.5


def test_l5_hold_offset_is_b_over_att_kp(ctx, capsys):
    su = ctx["su"]
    plant = dataclasses.replace(ctx["plant5"], coupling=False)
    att, plan = _hold(ctx, HOLD_EXECUTIONS)
    kw = {"attitude": att, "rotor0": _rest_speeds(plant, plan.thrust_n), "dshot": bd.DSHOT_OFF}
    law = bd.l5_law(ctx["p5"])
    nominal = bd.run(law, _lpf(su), plant, plan, plan.thrust_n, bias=(0.0, 0.0, 0.0), **kw)
    assert all(x == 0.0 for col in nominal["w"] for x in col) and all(q == bd.IDENTITY for q in nominal["q"])
    kp = su.cfg.kp
    lines = []
    for a in HOLD_AXES:
        signs = tuple(1 if i == a else 0 for i in range(6))
        b = bd.gyro_bias(signs)[a]
        res = bd.run(law, _lpf(su), plant, plan, plan.thrust_n, bias=bd.gyro_bias(signs), **kw)
        err = rm.channels(res["q"][-1], [res["w"][i][-1] for i in range(3)])
        r_end = rm.law(su.cfg, res["q"][-1], bd.IDENTITY)[a]
        bound = offset_bound(r_end, b, kp)
        lines.append(f"(6 b) L5 hold, gyro {fe.AXES[a]} +bound: delta err at the end {err[a]:.9e}, b / att_kp "
                     f"{b / kp:.9e}, difference {err[a] - b / kp:+.3e} (bound {bound:.3e}; r_end - b {r_end - b:+.3e})")
        assert abs(err[a] - b / kp) <= bound, a
        assert abs(err[a] - b / (FINE_FACTOR * kp)) > bound, a  # control: att_kp x 1.1
        assert all(err[i] == 0.0 for i in range(3) if i != a)
    _say(capsys, *lines)


