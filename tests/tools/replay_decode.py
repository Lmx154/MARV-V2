"""The decoded values of a received byte stream, for the replay tests and the script that records their fixture (ground-segment unit GX-11).

Decodes with the MARV dialect generated by pymavlink's mavgen from link/marv.xml and the pinned standard definitions (tools/link/fetch_defs.py,
cached in a directory the caller gives; the same generation as tools/gs/e2e_fake_vehicle.py): a test tool, so GS-3 allows this file to name the
dialect. A stream of bytes becomes a list of dicts {"type", "seq", "src", "fields"} in the order the frames were received, with every field in a
form that JSON carries without loss (a NaN is the text "nan", bytes are hex). Two decodings are equal iff the same frames arrived with the same
values; a frame that fails its checksum is dropped by the parser, so it is missing from the list.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "gs"))
import e2e_fake_vehicle  # noqa: E402  (its load_dialect is the dialect generation the GCS end-to-end test uses)


def load_dialect(defs_dir: Path):
    return e2e_fake_vehicle.load_dialect(Path(defs_dir))


def normal(value):
    if isinstance(value, float):
        return "nan" if math.isnan(value) else value
    if isinstance(value, (bytes, bytearray)):
        return bytes(value).hex()
    if isinstance(value, (list, tuple)):
        return [normal(v) for v in value]
    return value


def decode(dialect, data: bytes) -> list[dict]:
    parser = dialect.MAVLink(None)
    parser.robust_parsing = True
    out = []
    for m in parser.parse_buffer(data) or []:
        if m.get_type() == "BAD_DATA":
            continue
        out.append({"type": m.get_type(), "seq": m.get_seq(), "src": [m.get_srcSystem(), m.get_srcComponent()],
                    "fields": {name: normal(getattr(m, name)) for name in m.get_fieldnames()}})
    return out
