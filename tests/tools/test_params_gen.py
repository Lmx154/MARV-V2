def test_duplicate_name_across_files_is_refused(tmp_path):
    a = write(tmp_path, good_entry("mass"), "a.yaml")
    b = write(tmp_path, good_entry("mass"), "b.yaml")
    r = run_gen(tmp_path, ("card", a), ("register", b))
    assert r.returncode == 1
    assert "mass" in r.stderr and "duplicate" in r.stderr and "a.yaml" in r.stderr
    assert not (tmp_path / "out").exists()


