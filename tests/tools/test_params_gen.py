def test_order_follows_the_sources(tmp_path):
    a = write(tmp_path, good_entry("zeta") + good_entry("alpha"), "a.yaml")
    b = write(tmp_path, good_entry("mid"), "b.yaml")
    assert run_gen(tmp_path, ("card", a), ("register", b)).returncode == 0
    ids = re.findall(r"^  (\w+) = (\d+),$", read_out(tmp_path)["param_ids.hpp"].decode(), re.M)
    assert ids == [("zeta", "0"), ("alpha", "1"), ("mid", "2")]


def hash_of(tmp_path, text, out):
    src = write(tmp_path, text, f"{out}.yaml")
    r = run_gen(tmp_path, ("card", src), out=out)
    assert r.returncode == 0, r.stderr
    return header_hash(read_out(tmp_path, out)["param_ids.hpp"].decode())


def test_schema_hash_changes_on_rename_retype_reunit_not_on_value(tmp_path):
    base = hash_of(tmp_path, good_entry("mass"), "base")
    assert hash_of(tmp_path, good_entry("mass2"), "renamed") != base
    assert hash_of(tmp_path, good_entry("mass", type="i32", value=3), "retyped") != base
    assert hash_of(tmp_path, good_entry("mass", unit="g"), "reunited") != base
    assert hash_of(tmp_path, good_entry("mass", value=123.5, sigma=9.0, source='"other"', method="measured"),
                   "revalued") == base


def test_schema_hash_depends_on_order(tmp_path):
    ab = hash_of(tmp_path, good_entry("a") + good_entry("b"), "ab")
    ba = hash_of(tmp_path, good_entry("b") + good_entry("a"), "ba")
    assert ab != ba


def test_schema_hash_is_the_documented_sha256_prefix(tmp_path):
    import hashlib

    digest = hashlib.sha256(b"mass\x1ff32\x1fkg\x1e").digest()
    assert hash_of(tmp_path, good_entry("mass"), "doc") == int.from_bytes(digest[:8], "big")


def test_float_round_trip_is_exact(tmp_path):
    values = [0.1, 0.033, 1.0e-6, 1.5625e-6, 3.4028234663852886e38, 1.401298464324817e-45, 16777217.0, -0.0, 1.0,
              123456.789, 2.0**-100]
    text = "".join(good_entry(f"v{i}", value=repr(v), sigma="0") for i, v in enumerate(values))
    src = write(tmp_path, text)
    assert run_gen(tmp_path, ("card", src)).returncode == 0
    cpp = read_out(tmp_path)["param_defaults.cpp"].decode()
    literals = re.findall(r"\{\{ParamType::F32, (\S+?)f, 0\}", cpp)
    assert len(literals) == len(values)
    for lit, v in zip(literals, values, strict=True):
        assert "." in lit or "e" in lit, lit
        expected = struct.unpack("<f", struct.pack("<f", v))[0]
        got = struct.unpack("<f", struct.pack("<f", float(lit)))[0]
        assert struct.pack("<f", got) == struct.pack("<f", expected), (lit, v)


