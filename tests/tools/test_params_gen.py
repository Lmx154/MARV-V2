import importlib.util
import json
import re
import struct
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "tools" / "gen" / "params_gen.py"
FIXTURES = ROOT / "tests" / "fixtures" / "params"
_spec = importlib.util.spec_from_file_location("params_gen", GEN)
gen = importlib.util.module_from_spec(_spec)
sys.modules["params_gen"] = gen
_spec.loader.exec_module(gen)

GOOD = {
    "type": "f32",
    "value": "0.75",
    "unit": "kg",
    "method": "scenario",
    "source": '"test data"',
    "sigma": "0.01",
}


def entry_yaml(name, **fields):
    body = ", ".join(f"{k}: {v}" for k, v in fields.items() if v is not None)
    return f"{name}: {{{body}}}\n"


def good_entry(name="p", **overrides):
    """One YAML entry; override values are raw YAML text, None drops the field."""
    fields = {**GOOD, **{k: (v if v is None or isinstance(v, str) else repr(v)) for k, v in overrides.items()}}
    return entry_yaml(name, **fields)


def run_gen(tmp_path, *sources, out="out"):
    args = [sys.executable, str(GEN)]
    for kind, path in sources:
        args += [f"--{kind}", str(path)]
    args += ["--out-dir", str(tmp_path / out)]
    return subprocess.run(args, capture_output=True, text=True, check=False)


def write(tmp_path, text, name="src.yaml"):
    p = tmp_path / name
    p.write_text(text)
    return p


def fixture_sources():
    return [("card", FIXTURES / "l0_card.yaml"), ("register", FIXTURES / "l0_register.yaml")]


def read_out(tmp_path, out="out"):
    d = tmp_path / out
    return {f: (d / f).read_bytes() for f in ("param_ids.hpp", "param_defaults.cpp", "params_manifest.json")}


def header_hash(header: str) -> int:
    return int(re.search(r"kParamSchemaHash = 0x([0-9a-f]{16})ULL", header).group(1), 16)


def refused(tmp_path, text, *needles):
    r = run_gen(tmp_path, ("card", write(tmp_path, text)))
    assert r.returncode == 1, r.stdout + r.stderr
    for needle in needles:
        assert needle in r.stderr, r.stderr
    assert not (tmp_path / "out").exists(), "a refused run must write nothing"
    return r


def test_fixture_generates(tmp_path):
    r = run_gen(tmp_path, *fixture_sources())
    assert r.returncode == 0, r.stderr
    out = read_out(tmp_path)
    assert out["param_ids.hpp"].startswith(b"// Generated by tools/gen/params_gen.py")


